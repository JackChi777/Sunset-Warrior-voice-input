def _load_terms_file(path: str, tag: str, n: int) -> int:
    """读单个词表文件写入 jieba 用户词典。行格式：`word score`（score 可选，1.0~5.0；默认 2.0）。"""
    if not path or not os.path.exists(path):
        return n
    try:
        with open(path, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith('#'):
                    continue
                parts = line.split()
                if not parts:
                    continue
                word = parts[0]
                try:
                    score = float(parts[1]) if len(parts) > 1 else 2.0
                except (ValueError, IndexError):
                    score = 2.0
                # jieba.add_word：freq 越大越不会在分词时被切碎
                freq = int(max(0.5, min(score, 10.0)) * 1000)
                try:
                    jieba.add_word(word, freq=freq, tag=tag)
                except Exception:
                    jieba.add_word(word, freq=freq)
                n += 1
    except Exception as e:
        print(f'[warn] 加载词表失败 {path}: {e}')
    return n


