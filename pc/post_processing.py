# ===================== 档位 4 保护：的/地/得 互换仲裁 =====================
# 用户采纳 / 手动保存的「的↔地↔得」调整，若与规则层（档位 1）对同一处的
# 判定相悖，拒绝学成全局替换规则。典型误学场景：
#   - 复合名词被误改：深入的研究能力→深入地研究能力（规则层判定 的 才对）；
#   - 名动词宾语被误改：做了认真的检查→做了认真地检查（规则层判定 的 才对）；
#   - 状语形容词被误改：小心地处理文件→小心的处理文件（规则层判定 地 才对）；
#   - HanLP dep 层把名词定语误改后又被采纳：三个月的时间→三个月得时间。
# 仲裁失败（规则层不可用 / 文本长度被 fixed 表增删）时保守放行，不阻塞正常学习。
@functools.lru_cache(maxsize=256)
def _de_rule_verdict(raw: str) -> Optional[str]:
    """规则层对 raw 的完整判定；仅当长度不变（fixed 表未增删字）时返回结果。"""
    try:
        out = correct_de_di_de(raw)
    except Exception:
        return None
    return out if len(out) == len(raw) else None


def _de_swap_conflicts_with_rule(raw: str, i1: int, new_char: str) -> bool:
    """raw[i1] 处若把 de 字改成 new_char，是否与规则层判定冲突。

    规则层认为该处应为 X，而学习方向是 的→Y（X≠Y）→ 冲突，拒绝学习；
    规则层恰好也改成 Y（或保持 Y）→ 一致，放行。
    """
    verdict = _de_rule_verdict(raw)
    if verdict is None or i1 >= len(verdict):
        return False
    return verdict[i1] != new_char


def _de_swap_conflicts_rule_only(raw: str, corrected: str) -> bool:
    """raw→corrected 的差异中是否存在「被规则层否决的 的地得 单字互换」。

    供 main.py 的整句精确映射兑底使用：diff 被拒后若整句照存，会把与规则层
    相悖的修正（如 做了认真的检查→做了认真地检查）学成精确映射，绕开仲裁。
    仅当所有 diff 都被拒、且其中有规则层相悖的 de 互换时返回 True（此时应
    整句也不学）。
    """
    if not raw or not corrected or raw == corrected:
        return False
    from difflib import SequenceMatcher as _SM

    sm = _SM(a=raw, b=corrected)
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag != 'replace':
            continue
        old = raw[i1:i2]
        new = corrected[j1:j2]
        if (len(old) == 1 and len(new) == 1
                and old in '的地得' and new in '的地得' and old != new
                and _de_swap_conflicts_with_rule(raw, i1, new)):
            return True
    return False


# 与 confusion_corrector._ORIG_NEIGHBOR_MIN_FREQ 一致：freq ≥ 50 视为「可靠成词」
_WORD_MIN_FREQ = 50


def _jieba_freq(word: str) -> int:
    """查询 jieba 词典词频（freq < _WORD_MIN_FREQ 视为不成词/冷僻异体词）。"""
    try:
        import jieba

        jieba.initialize()
        return int(jieba.dt.FREQ.get(word, 0))
    except Exception:
        return 0


def _expand_single_char_diff(raw: str, corrected: str,
                             i1: int, i2: int, j1: int, j2: int):
    """单字 diff X→Y 的安全化：只在「扩成 ≥2 字规则且旧形式不成词」时学习。

    按侧守卫——左扩要求左侧 bigram（aX）不成词，右扩要求右侧 bigram（Xa）
    不成词。这样 安照→按照 能走右扩（请安 是合法词，左扩会误伤 请安，但
    右扩 安照 不成词、安全）；天真→天很 则被 天真 挡住（X 属合法词）。
    返回 (old, new, i1, i2, j1, j2) 或 None（附带扩展后的跨度，供词尾对齐用）：
      - 凑和→凑合：aX=凑和 不成词 → 左扩 ("凑和","凑合", 0,2,0,2)；
      - 安照→按照：左扩被 请安 挡，右扩 Xa=安照 不成词 → ("安照","按照")；
      - 天真→天很：左扩被 天真 挡、右扩 Xa=真开 不成词 → 只可能学 (
        "真开","很开") 这种罕见 bigram 的受限规则，不会出现全局 真→很。
    """
    if not (i2 - i1 == 1 and j2 - j1 == 1):
        return None
    # 左扩（前缀相同）：aX → aY；要求 aX 不成词
    if (i1 > 0 and j1 > 0
            and raw[i1 - 1] == corrected[j1 - 1]
            and raw[i1 - 1] not in _GENERAL_DIFF_PUNCT_CHARS
            and _jieba_freq(raw[i1 - 1:i2]) < _WORD_MIN_FREQ):
        return (raw[i1 - 1:i2], corrected[j1 - 1:j2], i1 - 1, i2, j1 - 1, j2)
    # 右扩（后缀相同）：Xa → Ya；要求 Xa 不成词
    if (i2 < len(raw) and j2 < len(corrected)
            and raw[i2] == corrected[j2]
            and raw[i2] not in _GENERAL_DIFF_PUNCT_CHARS
            and _jieba_freq(raw[i1:i2 + 1]) < _WORD_MIN_FREQ):
        return (raw[i1:i2 + 1], corrected[j1:j2 + 1], i1, i2 + 1, j1, j2 + 1)
    return None


def _extend_to_word_boundary(raw: str, corrected: str,
                             i1: int, i2: int, j1: int, j2: int,
                             max_len: int = 6):
    """把 diff 沿『紧随其后的相等片段』向右扩展到整词（词尾对齐）。

    difflib 是字符级的：大摸型→大模型 中 型 是相等尾巴，diff 只剩 大摸→大模，
    学到的是残片规则（大摸 大模 都不成词，同音展开也会因目标不成词而失效）。

    扩展条件（严格，只对准『听错词 → 真实词』）：
      - 基础 old 不成词（freq < 50）——是 ASR 听错而非用户有意改写（电脑→计算机
        中 电脑 成词，不扩展）；
      - 扩展后 old2 仍不成词 且 new2 首次成词（freq >= 50）——目标对准真实词；
      - 长度受 max_len 约束。
    例：大摸|型→大模|型 → 学 (大摸型,大模型)；摄象|机→摄像|机 → (摄象机,摄像机)；
    凑和|一下→凑合|一下 扩展后 new2 不成词 → 不扩展，保持 (凑和,凑合)。
    返回 (old2, new2) 或 None。
    """
    old = raw[i1:i2]
    new = corrected[j1:j2]
    if len(old) < 2 or len(new) < 2:
        return None
    if _jieba_freq(old) >= _WORD_MIN_FREQ:
        return None
    if _jieba_freq(new) >= _WORD_MIN_FREQ:
        # new 侧本身已是真实词（摄象→录像 / 凑和→凑合）：规则已经够好，
        # 扩展只会把宽覆盖收窄成单场景，不做。只在 new 是残片
        # （大模 不成词）时才升级成整词规则。
        return None
    # 紧随其后的最长相等 run（受 max_len 约束，避免扩出整句）
    k = 0
    while (i2 + k < len(raw) and j2 + k < len(corrected)
           and raw[i2 + k] == corrected[j2 + k]
           and len(old) + k + 1 <= max_len):
        k += 1
    for kk in range(k, 0, -1):
        old2 = raw[i1:i2 + kk]
        new2 = corrected[j1:j2 + kk]
        if (_jieba_freq(old2) < _WORD_MIN_FREQ
                and _jieba_freq(new2) >= _WORD_MIN_FREQ):
            return (old2, new2)
    return None


def extract_general_diff(raw: str, corrected: str, max_len: int = 6) -> list:
    """档位 4 扩展：从 raw → corrected 中抽取所有可学习的字符级 diff。

    与 extract_dedede_diff 的区别：
    - 不限制『含 的/地/得』，覆盖错别字 / 词序错 / ASR 同音异形 / 术语替换 / 口语删除等

    过滤规则（「越能学」主动控制）：
    1. 长度上限：old / new 均 ≤ max_len，默认 6 字符
    2. 跨标点不入（避免句间语法跟串到一起）
    3. 调换类不入（联合全部 diff 后 set 后仍相同），避免『重要非常』↔『非常重要』被误学
    4. 纯删除只学口语残留白名单（嗯/那个/就这样等）

    Returns:
        [(old, new), ...]
    """
    if not raw or not corrected or raw == corrected:
        return []
    from difflib import SequenceMatcher as _SM

    sm = _SM(a=raw, b=corrected)
    # 收集所有非 equal 片段及其在原文/新文中的起止位置（用于跨标点判定 + 单字扩写）
    parts: list = []  # (old, new, i1, i2, j1, j2)
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == 'equal':
            continue
        parts.append((raw[i1:i2], corrected[j1:j2], i1, i2, j1, j2))

    if not parts:
        return []

    # 过滤 3：整句纯调换（anagram）→ 全部拒绝。
    # 例：重要非常↔非常重要、数据加↔加数据、ab↔ba。
    # 注意：不能用「非 equal 片段拼接」做 anagram——difflib 会因中间
    # 存在 equal 块（如『重要』）把调换拆成 insert/delete 两段，拼接后
    # 两侧反而相等，漏掉调换。用整句字符多重集判断最稳。
    if sorted(raw) == sorted(corrected):
        return []

    diffs: list = []
    for old, new, i1, i2, j1, j2 in parts:
        # 过滤 1：长度上限
        if len(old) > max_len or len(new) > max_len:
            continue
        # 过滤 2：跨标点不入——diff 片段内部含标点
        if any(ch in old + new for ch in _GENERAL_DIFF_PUNCT_CHARS):
            continue
        # 过滤 2b：跨标点不入——diff 紧跟在标点之后（独立分句/段的局部改动，
        # 如『你好。世界→你好。world』），避免把跨句关联学成全局替换。
        if (i1 > 0 and raw[i1 - 1] in _GENERAL_DIFF_PUNCT_CHARS) or (
            j1 > 0 and corrected[j1 - 1] in _GENERAL_DIFF_PUNCT_CHARS
        ):
            continue
        # 过滤 4：纯删除（new == ''）只学口语残留白名单
        if not new and old not in _GENERAL_DIFF_FILLER_WORDS:
            continue
        # 过滤 5：纯 的地得 互换（两侧其余字符完全一致）→ 一律不学。
        # 的地得 由规则层（档位 1）自己修正：一致方向学了冗余，相悖方向学了
        # 污染（做了认真的检查→做了认真地检查 会被学成 的→地 全局规则）。
        if (old and new and len(old) == len(new)
                and all(a == b or (a in '的地得' and b in '的地得')
                        for a, b in zip(old, new))
                and any(a != b for a, b in zip(old, new))):
            continue
        # 过滤 5c：单字修改 → 仅当「旧字不属于任何合法词」时扩成 ≥2 字规则学。
        # 例：凑和→凑合（凑和 freq 0）→ 学 ("凑和","凑合")；天真→天很（天真
        # freq 高）→ 拒学。单字全局规则（的→得/真→很/令→让/好→不错）会拆
        # 我的电脑/认真/命令/你好。纯插入（old==''）无意义，一并跳过。
        if new and len(old) < 2:
            if len(old) == 1:
                expanded = _expand_single_char_diff(
                    raw, corrected, i1, i2, j1, j2
                )
                if expanded is not None:
                    e_old, e_new, e_i1, e_i2, e_j1, e_j2 = expanded
                    # 词尾对齐：大摸|型→大模|型 → 扩到整词 (大摸型,大模型)
                    ext = _extend_to_word_boundary(
                        raw, corrected, e_i1, e_i2, e_j1, e_j2, max_len
                    )
                    diffs.append(ext if ext is not None else (e_old, e_new))
            continue
        # 词尾对齐（多字 diff 同理）：残片规则扩到整词，目标成词才扩
        ext = _extend_to_word_boundary(
            raw, corrected, i1, i2, j1, j2, max_len
        )
        if ext is not None:
            diffs.append(ext)
        else:
            diffs.append((old, new))
    return diffs


