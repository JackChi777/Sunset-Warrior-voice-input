def should_add_to_user_dict(word: str) -> bool:
    """A 档词表双通道：修正产生的新词（jieba 不认识）是否值得沉淀进用户词表。

    守卫：多字 / 纯安全字符 / 至少一个汉字 / 不含 的地得（避免把 好的很 这类
    补语结构当词收录）/ jieba 不认识（freq < 50）/ 不在用户词表已有词中。
    """
    if not word or len(word) < 2:
        return False
    if any(ch in word for ch in '的地得'):
        return False
    if any(ch in word for ch in ' \t\n，。！？、；：""''（）《》【】,.:;!?\'"'):
        return False
    if not any('\u4e00' <= ch <= '\u9fff' for ch in word):
        return False
    if _jieba_freq(word) >= _WORD_MIN_FREQ:
        return False
    if word in _user_terms_words():
        return False
    return True


def add_word_to_user_dict(word: str, score: float = 2.0,
                          path: Optional[str] = None) -> bool:
    """把 word 追加进用户词表文件并立即写入 jieba（当前会话即生效）。

    失败/不合规一律返回 False，不抛异常（锦上添花逻辑绝不打断主流程）。
    """
    if not should_add_to_user_dict(word):
        return False
    path = path or _DEFAULT_USER_TERMS_PATH
    try:
        if path:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'a', encoding='utf-8') as f:
                f.write(f'{word} {score:g}\n')
    except Exception as e:
        print(f'[warn] 用户词表写入失败 {word}: {e}')
        return False
    try:
        import jieba
        freq = int(max(0.5, min(score, 10.0)) * 1000)
        try:
            jieba.add_word(word, freq=freq, tag='n')
        except Exception:
            jieba.add_word(word, freq=freq)
    except Exception:
        pass
    return True


# ============ 档位 4.6：自学习规则存储（B 档确认制）============
# 目的：根治「一次口误学成永久全局规则」。
# - 精确规则（exact）：同一 old→new 需在 ≥2 个不同句子中出现（用户两次独立
#   修正同一错误）才升级为全局替换；第一次只登记待确认，不全局生效。
# - 同音变体（variants）：自动生成的变体永远无法被用户直接确认（用户只输入
#   原形），所以变体跟随其基础规则——base 升级为全局时，变体才一起激活。
# - 独立存储 learned_rules.json，不进 config.replacements（那是用户手动表，
#   学习内容与其分开，互不污染）；应用优先级低于用户手动规则。

import hashlib

_DEFAULT_LEARNED_RULES_PATH = os.path.join(
    _DATA_DIR, 'user_data', 'learned_rules.json'
)
_PROMOTE_THRESHOLD = 2  # 跨不同句子出现 ≥2 次才升级为全局替换


def _load_learned_rules(path: Optional[str] = None) -> dict:
    """读自学习规则库；损坏/缺失返回空结构（永不抛异常）。"""
    path = path or _DEFAULT_LEARNED_RULES_PATH
    try:
        if path and os.path.exists(path):
            import json
            with open(path, 'r', encoding='utf-8') as f:
                data = json.load(f)
            if isinstance(data, dict):
                return data
    except Exception as e:
        print(f'[warn] 自学习规则库读取失败: {e}')
    return {}


def _save_learned_rules(data: dict, path: Optional[str] = None) -> bool:
    """写自学习规则库。失败返回 False（锦上添花逻辑绝不打断主流程）。"""
    path = path or _DEFAULT_LEARNED_RULES_PATH
    try:
        if path:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            import json
            with open(path, 'w', encoding='utf-8') as f:
                json.dump(data, f, ensure_ascii=False, indent=2)
            return True
    except Exception as e:
        print(f'[warn] 自学习规则库写入失败: {e}')
    return False


def record_learned_rule(old: str, new: str, raw: str,
                        kind: str = 'exact',
                        base: Optional[tuple] = None,
                        path: Optional[str] = None,
                        promote_now: bool = False) -> str:
    """登记一次用户修正，返回动作：

    exact: 'new'（首次登记待确认）/ 'counted'（重复句子，无新证据）/
           'promoted'（跨不同句子达阈值，升级为全局）/ 'error'（写盘失败）
    variant: 'variant'（新登记）/ 'duplicate'（已存在）/ 'error'

    promote_now: 为 True 时直接升级为全局替换（用于用户手动编辑明确纠正的
    来源，如「保存手动修正」——用户明白改什么，不应等跨句子累计）。
    """
    data = _load_learned_rules(path)
    key = old + '\u0000' + new
    raw_hash = hashlib.md5(raw.encode('utf-8')).hexdigest()[:16]
    if kind == 'variant':
        variants = data.setdefault('variants', {})
        if key not in variants:
            variants[key] = {
                'old': old, 'new': new,
                'base': (base[0] + '\u0000' + base[1]) if base else key,
            }
            return 'variant' if _save_learned_rules(data, path) else 'error'
        return 'duplicate'
    rules = data.setdefault('exact', {})
    entry = rules.get(key)
    if entry is None:
        rules[key] = {'old': old, 'new': new, 'count': 1,
                      'promoted': bool(promote_now), 'raws': [raw_hash]}
        return ('promoted' if promote_now else 'new') if _save_learned_rules(data, path) else 'error'
    if raw_hash not in entry.get('raws', []):
        entry.setdefault('raws', []).append(raw_hash)
        entry['count'] = len(entry['raws'])
    if promote_now:
        entry['promoted'] = True
        action = 'promoted'
    elif (not entry.get('promoted')
            and entry.get('count', 1) >= _PROMOTE_THRESHOLD):
        entry['promoted'] = True
        action = 'promoted'
    else:
        action = 'counted'
    return action if _save_learned_rules(data, path) else 'error'


def get_applied_learned_rules(path: Optional[str] = None) -> list:
    """当前应全局生效的自学习规则：已升级的精确规则 + 已升级 base 的同音变体。"""
    data = _load_learned_rules(path)
    applied: list = []
    exact = data.get('exact') or {}
    promoted_bases = set()
    for key, e in exact.items():
        if e.get('promoted'):
            promoted_bases.add(key)
            applied.append((e.get('old', ''), e.get('new', '')))
    for v in (data.get('variants') or {}).values():
        if v.get('base') in promoted_bases:
            applied.append((v.get('old', ''), v.get('new', '')))
    return applied


def apply_learned_rules(text: str, path: Optional[str] = None) -> str:
    """应用已升级的自学习规则（纯字符串替换，与用户手动替换同机制）。"""
    for old_word, new_word in get_applied_learned_rules(path):
        if old_word and new_word and old_word in text:
            text = text.replace(old_word, new_word)
    return text


def clear_learned_rules(path: Optional[str] = None) -> bool:
    """清空自学习规则库（设置界面『清空』按钮）。"""
    return _save_learned_rules({'exact': {}, 'variants': {}}, path)


