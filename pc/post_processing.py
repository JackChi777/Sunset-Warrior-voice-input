    def add_punctuation(self, text: str) -> str:
        """使用代码规则添加标点符号"""
        if not text:
            return text

        try:
            # 简单的标点添加规则
            # 在句子中间添加逗号
            punctuated_text = re.sub(r'([，。！？])', '', text)  # 先移除现有标点

            # 在常见连接词后添加逗号
            for connector in ['然后', '但是', '而且', '虽然', '因为', '所以', '如果', '当']:
                punctuated_text = punctuated_text.replace(connector, connector + '，')

            # 在疑问词后添加问号
            for qw in self.punctuation_rules['question_words']:
                if qw in punctuated_text:
                    # 在疑问词后添加问号
                    punctuated_text = re.sub(f'({qw})([^？]*)', r'\1\2？', punctuated_text)
                    break

            # 在句子结尾添加句号
            if punctuated_text and not punctuated_text[-1] in '。！？':
                punctuated_text += '。'

            # 清理重复标点
            punctuated_text = re.sub(r'([。！？，]){2,}', r'\1', punctuated_text)

            return punctuated_text

        except Exception as e:
            print(f"标点添加失败: {e}")
            return text

