class DeDiDeCorrector:
    """的/地/得 智能纠错器：固定词表 + 词性规则双重保障"""

    def __init__(self):
        self.fixed_phrases = _SORTED_FIXED_PHRASES

    def correct_fixed_phrases(self, text: str) -> str:
        """第一步：固定词表替换（零误伤，最高优先级）

        表内混有常见错别字项（安祥/凑和/做月子…），这些项复用
        _TYPO_FIXES_GUARDS 子串守卫（平安祥和/拼凑和/叫做月子 不得误伤）。
        """
        for wrong, right in self.fixed_phrases:
            text = _guarded_replace(text, wrong, right)
        return text

    MAX_TOKEN_DISTANCE = 8  # POS 跨词距离上限

    def _map_words_to_chars(self, text, words):
        """jieba 分词 → 字符级位置 [(word, flag, start, end), ...]"""
        positions = []
        idx = 0
        for w in words:
            w_word = w.word
            if not w_word:
                continue
            start = text.find(w_word, idx)
            if start == -1:
                start = idx
            end = start + len(w_word)
            positions.append((w_word, POS_OVERRIDES.get(w_word, w.flag), start, end))
            idx = end
        return positions

    @staticmethod
    def _replace(chars, start, end, new_char):
        for pos in range(start, end):
            if pos < len(chars):
                chars[pos] = new_char

    def _has_nominal_determiner(self, positions, adj_idx):
        """形容词左侧是否存在「数量/指示限定词」（这个处理/很多要求/一种研究）。

        只跨过副词（很/非常/特别 等）向左扫描；一旦遇到名词/动词/代词（如主语
        “这个团队”的“团队”）即停止，避免把主语前的“这个”误当成中心语限定词。
        """
        for j in range(adj_idx - 1, max(-1, adj_idx - 5), -1):
            w, flag = positions[j][0], positions[j][1]
            if w in _NOMINAL_DETERMINERS:
                return True
            if flag not in ADV_TAGS and w not in _NOMINAL_DETERMINERS:
                break
        return False

    def _has_np_object_verb(self, positions, adj_idx, verb_set=_NP_OBJECT_VERBS):
        """形容词左侧是否存在「接名词宾语」的动词（做了认真的检查/提出了具体的要求）。

        向左扫描时跨过 副词、体标记（了/着/过）与其它动词——
        「提出了具体的说明」里 了 夹在动词和形容词之间，不跨过就永远扫不到动词；
        遇到名词/代词/形容词/介词等非动词性成分即停止（避免把主语当宾语动词）。
        verb_set 参数用于区分双向安全（_STRICT_NP_OBJECT_VERBS）与
        仅规则 3 可用的全集（_NP_OBJECT_VERBS，含 开始/继续/负责 等 VP 动词）。
        """
        for j in range(adj_idx - 1, max(-1, adj_idx - 5), -1):
            w, flag = positions[j][0], positions[j][1]
            if w in verb_set:
                return True
            # 只跨过 副词/体标记（了/着/过）：做 了 认真 的 检查 → 做。
            # 不跨任意动词——否则「照我提到的办法去做也可能慢慢地恢复」里
            # 5 格外的 做（做 是「去做办法」的动词，不支配 恢复）会被误判成
            # 支配 恢复 的接名词宾语动词 → 地 被误改成 的（CGED 实证误改）。
            if flag in ADV_TAGS or w in _ASPECT_MARKERS:
                continue
            break
        return False

    def _has_object_preposition(self, positions, adj_idx):
        """形容词左侧是否存在「接名词宾语」的介词（经过认真的思考/通过深入的分析）。

        介词（经过/通过/根据/随着…）后接的必是名词性宾语，名动词在该结构里
        必作名词（→ 的）；介词宾语没有“状语 + 动词”的合法读法，双向安全。
        同样跨过副词与体标记（经过了认真的思考）。
        """
        for j in range(adj_idx - 1, max(-1, adj_idx - 5), -1):
            w, flag = positions[j][0], positions[j][1]
            if w in _OBJECT_PREPOSITIONS:
                return True
            if flag in ADV_TAGS or w in _ASPECT_MARKERS:
                continue
            break
        return False

    def _has_verb_measure_before(self, positions, adj_idx):
        """形容词左侧是否存在「动词 + 动量词」组合（做一遍 / 看一次 / 进行一番）。

        动量词（一遍/一次/一下…）紧跟动词时，后面的名动词必是宾语名词：
        「做一遍仔细地检查」→「做一遍仔细的检查」（检查是“做”的宾语）。
        这个信号对 的/地 两个方向都安全，不像“接名词动词”（开始/负责…）
        存在「开始 + 状语 + 动词」的歧义。
        """
        for j in range(adj_idx - 1, max(-1, adj_idx - 7), -1):
            w, flag = positions[j][0], positions[j][1]
            is_measure = (
                flag == 'm'
                or any(w.endswith(s) for s in ('一遍', '一下', '一次', '一番', '一回', '一场'))
            )
            if is_measure:
                # 动量词前允许跨过体标记找动词：做/了/一遍/认真/的/检查 → 做。
                # 否则「做了一遍认真的检查」会被扫不到 做 而误改成 地。
                k = j - 1
                while k >= 0 and positions[k][0] in _ASPECT_MARKERS:
                    k -= 1
                if k >= 0 and (positions[k][1] in STRICT_VERB_TAGS
                               or positions[k][0] in VERB_MEASURE_SUFFIXES):
                    return True
            if flag not in ADV_TAGS and not is_measure and w not in _ASPECT_MARKERS:
                break
        return False

    def _gerund_heads_compound(self, positions, gerund_idx):
        """动名词后接抽象属性名词 → 定语/复合名词（研究能力/管理经验/测试流程）。

        「ADJ + 的 + 名动词 + 抽象名词」里名动词几乎必是定语（复合名词）→ 的。
        典型动词宾语（问题/数据/文件/团队/设备/课程/英语…）不在
        _GERUND_COMPOUND_HEADS 里，仍是「状语 + 动宾」（认真地研究问题 → 地）。
        """
        if positions[gerund_idx][0] not in GERUND_NOUNS:
            return False
        nxt_idx = gerund_idx + 1
        if nxt_idx >= len(positions):
            return False
        w, flag = positions[nxt_idx][0], positions[nxt_idx][1]
        return flag in ('n', 'nr', 'ns', 'nt', 'nz') and w in _GERUND_COMPOUND_HEADS

    def _gerund_is_nominal(self, positions, de_idx, include_np_verb=True):
        """判断「的/地」之后的名动词是否作名词使用（→ 用「的」）。

        de_idx: 「的/地/得」在 positions 中的索引。
        信号：
          1) 形容词前有数量/指示限定词（这个处理 / 很多要求 / 一种研究）——
             对任何词都成立，因为「限定词 + A + 的 + V」里 V 必被名词化；
          2) 形容词前有接名词宾语的动词（负责真实的管理 / 做了认真的检查）；
          3) 形容词前有「动词 + 动量词」组合（做一遍仔细地检查 → 检查 是宾语）；
          4) 形容词前有接名词宾语的介词（经过认真的思考 / 通过深入的分析）；
          5) 动名词后接抽象属性名词（深入的研究能力 / 严格的管理流程）→ 复合名词。

        信号 2 对「地→的」方向（Rule 4）只开放 _STRICT_NP_OBJECT_VERBS
        （做/提出/提供/进行…纯接名词宾语）：这些动词后的名动词必是宾语名词。
        开始/继续/负责/需要 等可接 VP 补足语的动词被排除，因为
        「开始真实地处理」这类 VP 补足语（开始 + 状语 + 动词）里动词仍是动词，
        不能被改成「的」。信号 1/3/4 双向安全；信号 5 在「地→的」方向
        会与「认真地研究问题」冲突（问题 不在复合名词表里），仅规则 3 方向使用。
        """
        gerund_idx = de_idx + 1
        adj_idx = de_idx - 1
        if adj_idx < 0 or gerund_idx >= len(positions):
            return False
        if self._has_nominal_determiner(positions, adj_idx):
            return True
        if self._has_verb_measure_before(positions, adj_idx):
            return True
        if self._has_object_preposition(positions, adj_idx):
            return True
        if include_np_verb:
            # 规则 3（的→地）：全集（含 开始/继续/负责 等 VP 动词）
            if self._has_np_object_verb(positions, adj_idx, _NP_OBJECT_VERBS):
                return True
            if self._gerund_heads_compound(positions, gerund_idx):
                return True
        else:
            # 规则 4（地→的）：只用纯接名词宾语的动词（做了认真的检查）
            if self._has_np_object_verb(positions, adj_idx, _STRICT_NP_OBJECT_VERBS):
                return True
        return False

    def _gerund_is_verbal(self, positions, de_idx):
        """判断「的/地」之后的名动词是否作动词使用（→ 用「地」）。

        信号：
          1) 后接指示限定词或体标记（配音这个片段 / 处理了 / 处理起来）→ 动词带宾语/体；
          2) 句尾且形容词前有真代词主语（他真实地配音）→ 谓语动词。
        """
        gerund_idx = de_idx + 1
        adj_idx = de_idx - 1
        if gerund_idx >= len(positions):
            return False
        if positions[gerund_idx][0] not in GERUND_NOUNS:
            return False
        # 向后扫最多 2 个 token 找「宾语起始词 / 体标记」：
        # 记录每一个步骤（每+一个）、处理这个问题（这个）→ 动词带宾语。
        if gerund_idx + 1 < len(positions):
            for k in (1, 2):
                nxt_idx = gerund_idx + k
                if nxt_idx >= len(positions):
                    break
                nxt = positions[nxt_idx]
                if nxt[0] in _OBJECT_START_DETERMINERS:
                    return True
                if nxt[0] in ('了', '着', '过', '起来', '下去'):
                    return True
                # CGED 2020/2021：后接名词/代词宾语 → 动词（深入地了解我们的文化 /
                # 充分地了解情况）。跳过标点/助词（充分的了解，并拥有 → 名词化，
                # 不算动词）。程度副词（很/太/非常…）后的名词是谓语补足语而非
                # 宾语（这个真实地处理很关键 → 处理 名词化，应改 的），遇到即停。
                if nxt[1] in NOUN_PRON_TAGS:
                    return True
                if nxt[0] in DEGREE_ADV_WORDS or (
                        nxt[1] in ('zg', 'd')
                        and nxt[0] in ('很', '太', '非常', '特别', '十分', '更', '最')):
                    break
                # 遇到标点/动词/句尾就停，避免把远处无关词当宾语
                if nxt[1] in STRICT_VERB_TAGS or nxt[0] in ('的', '地', '得'):
                    break
        # 句尾裸动名词 + 真代词主语：他真实地配音 / 我们认真地学习
        if gerund_idx == len(positions) - 1 and adj_idx - 1 >= 0:
            if positions[adj_idx - 1][0] in _TRUE_PRONOUNS:
                return True
        return False

    @staticmethod
    def _prep_has_verb(positions, de_idx):
        """A+的+为/给/向/对/跟 + (名词短语) + 动词 → 状语（努力地为...辩护）。

        介词(为/给/向/对/跟)后接名词宾语再接动词时，的 是 地 的误写
        （努力地为中国辩护 / 认真地对他说）。跳过最多 2 个名词/代词
        token 找动词；找不到（为+NP 结束、对+NP 结束）则不触发。
        """
        j = de_idx + 2
        for _ in range(3):
            if j >= len(positions):
                return False
            w, flag = positions[j][0], positions[j][1]
            if flag in STRICT_VERB_TAGS | {'vn'}:
                return True
            if flag not in NOUN_PRON_TAGS:
                return False
            j += 1
        return False

    @staticmethod
    def _is_last_content(positions, idx):
        """positions[idx] 是否为最后一个实义 token（其后只剩标点/空白）。"""
        for j in range(idx + 1, len(positions)):
            w = positions[j][0]
            if any('\u4e00' <= c <= '\u9fff' for c in w):
                return False
        return True

    def _adj_phrase_initial(self, positions, adj_idx):
        """adj_idx 之前的 token 是否全为副词/程度词/结构助词（无主语）。

        判定「短语开头」：快速的迭代（快速 在句首）→ True；
        他快速地迭代（他 主语）→ False；非常快速的迭代（非常 是副词）→ True。
        用于 句尾「形容词+的/地+动词」两种读法都合法时的保守守卫。
        """
        for j in range(adj_idx - 1, -1, -1):
            w, fl = positions[j][0], positions[j][1]
            if fl in ADV_TAGS or w in DEGREE_ADV_WORDS or w in NEG_DEGREE_ADVERBS:
                continue
            if fl in ('uj', 'uv', 'ud'):
                continue
            return False
        return True

    def _has_predicate_after(self, positions, de_idx, max_extra=4):
        """de_idx（的/地/得 所在）之后 max_extra 个 token 内是否有谓词性成分。

        用于「得+名词+谓词」补语保护：气得脸都红了 / 饿得肚子咕咕叫（咕咕 是
        拟声词 o，再往后 叫 才是动词）；名词 token 可能是补语小句的主语，跳过。
        """
        for k in range(1, max_extra + 1):
            j = de_idx + k
            if j >= len(positions):
                return False
            w, fl = positions[j][0], positions[j][1]
            # 谓词性：动词/形容词/副词。区别词 b（所有/这种…）不是谓词，
            # 且它在 ADJ_TAGS 里——若算谓词会跳过 规则 0.5 的“的”锁定，
            # 让后面的 规则 1 把 输入的所有数据 误改成 输入得所有数据。
            if fl in (VERB_TAGS | ADJ_TAGS | ADV_TAGS) and fl != 'b':
                return True
            if fl == 'o' or fl in ('uj', 'uv', 'ud'):
                continue
            if fl in NOUN_PRON_TAGS:
                continue
            return False
        return False

    def correct_by_pos(self, text: str) -> str:
        """档位 1 重构版：细粒度词性 + 句首保护 + 置信度门槛。

        关键改进（对照旧版）：
        - 用完整 prev_flag（vd/vn/nz 等），不再只取首字母
        - 句首"的...话/的时候/的确"独立结构不参与纠错
        - 距离门槛：prev 末尾到 next 开头 > MAX_TOKEN_DISTANCE 时跳过
        - 置信度门槛：歧义 case（如 a+的+v 但 a 不在白名单）跳过；
          已通过 fixed 表覆盖的就不再 surplus 修改
        """
        if not text or not text.strip():
            return text
        try:
            words = list(pseg.cut(text))
        except Exception:
            return text
        if len(words) < 3:
            return text

        chars = list(text)
        positions = self._map_words_to_chars(text, words)

        for i, (word, flag, start, end) in enumerate(positions):
            if word not in ('的', '地', '得'):
                continue

            # 句首独立结构保护：的确 / 的话 / 的时候 ...
            if word == '的':
                tail = text[end:end + 5]
                if any(tail.startswith(s[1:]) for s in SENTENCE_INITIAL_DE):
                    continue

            prev = positions[i - 1] if i > 0 else None
            nxt = positions[i + 1] if i + 1 < len(positions) else None
            if not prev or not nxt:
                # 句尾 得：X(形容词/名动词) + 得 句尾 → 的（这个是免费得 → 这个是免费的）。
                # ASR 把「这个是免费的」的 的 听成 得；句尾 的/地 一律不动。
                # 保护：情绪词感叹（他高兴得——）、DE_MORPHEME_VERBS（值得/记得）。
                # 注：不扩展到 动词(v)——分句后「他恨得，说不出话」的 得 在分句
                # 句尾会被误改；V+得+标点+连接词 由 correct_de_di_de 的字符级
                # 预修正处理（_DE_COMMA_CONNECTIVE_RE，能看见逗号）。
                if (word == '得' and prev
                        and prev[1] in ADJ_TAGS | {'vn', 'an'}
                        and prev[0] not in DE_MORPHEME_VERBS
                        and prev[0] not in _EMOTION_EXCLAM_ADJS):
                    self._replace(chars, start, end, '的')
                continue
            prev_word, prev_flag, _ps, prev_end = prev
            next_word, next_flag, next_start, _ne = nxt

            # 距离门槛
            if next_start - prev_end > self.MAX_TOKEN_DISTANCE:
                continue

            # ---------- 规则 0.8：V + 的/地/得 + 领属情绪名词 + 方位词(中/里/内) → 的 ----------
            # CGED 真实误改：相遇的喜悦中 / 重逢的快乐里 —— 喜悦(a 标) 被规则 1/2
            # （V+的+A→得）当状态补语改成 得，实际是「定语+领属」（…的喜悦）。
            # 真补语词（高兴/开心/快乐…跑得开心）在 VERB_COMPLEMENT_LIKE，不进本表；
            # 且只限方位词 中/里/内，「跑得开心时/前」补语+时点结构不受影响。
            if (word in ('的', '地', '得')
                    and prev_flag in VERB_TAGS
                    and next_word in _POSSESSIVE_EMOTION_NOUNS
                    and i + 2 < len(positions)
                    and positions[i + 2][0] in ('中', '里', '内')):
                self._replace(chars, start, end, '的')
                continue

            # ---------- 规则 0：V + 的/地/得 + 系词 → 的（名词化） ----------
            if prev_flag in STRICT_VERB_TAGS and next_word in COPULA_VERBS:
                self._replace(chars, start, end, '的')
                continue

            # ---------- 规则 0.6c：X + 得 + 语气词 → 的（那是免费得呀 → 那是免费的呀） ----------
            # ASR 把「的」误听成「得」的另一种高频模式：的 后接语气词（呀/呢/吧/
            # 啊/吗/嘛…）时，「是免费的呀」「好的呢」的 的 被听成 得。
            # 触发：prev 为 形容词/名动词（免费/好/漂亮/清楚），next 为语气词(y)。
            # 保护：情绪/状态形容词（高兴/激动…）+ 得 + 语气词 = 感叹/程度补语
            # （他高兴得呀——）必须保留；DE_MORPHEME_VERBS（值得/记得/觉得）保护；
            # 纯动词（跑/睡/唱）不触发（跑得呀 保留，交给语境）。
            if (word == '得'
                    and next_flag == 'y'
                    and prev_flag in ADJ_TAGS | {'vn', 'an'}
                    and prev_word not in DE_MORPHEME_VERBS
                    and prev_word not in _EMOTION_EXCLAM_ADJS):
                self._replace(chars, start, end, '的')
                continue

            # ---------- 规则 0.6：X + 得 + 裸名词 → 的（定语/领属，得 为同音误写） ----------
            # 与规则 4/4.5 的「地→的」对应：ASR 常把「的」误听成「得」（同音 de）。
            # 语法上「得」必须后接补语（形容词/动词/小句），后接裸名词时必是定语/领属 → 的。
            # 触发：前词为 形容词/名词，后词为名词性（漂亮得花朵/蓝色得天空/书得内容）。
            # 保护（主谓补语）：得 + 名词 + 谓语性成分 → 「气得脸都红了」「紧张得手心冒汗」，
            #   此时名词是补语小句的主语，保留「得」（否则误改成“气的心…”/“紧张的手心…”）。
            # 另注：代词+得+名词（我得回家/你得奖学金）里「得」多为动词/助动词，这里不做处理。
            # 再保护：prev 为「长」时跳过——预修正层已把 长的X→长得X（X 为外观词），
            # 且 长+得 只可能是「长得」（成长/看起来义，长得一样/长得人模人样），
            # 绝不可能是 得 误写的 的；否则「长的一样」会被改回「长的一样」。
            if (word == '得'
                    and prev_flag in (ADJ_TAGS | {'n', 'nr', 'ns', 'nt', 'nz'} | VERB_TAGS)
                    and next_flag in NOUN_PRON_TAGS | {'vn', 'an'}
                    and prev_word not in DE_MORPHEME_VERBS
                    and prev_word != '长'):
                # 补语保护 A：后接谓词性成分（前向扫描）→ 主谓补语小句（气得脸都红了）
                if self._has_predicate_after(positions, i):
                    continue
                # 补语保护 B：句尾低词频名词 → 被错标为名词的 VP 补语
                # （激动得流眼泪 / 热得满头大汗 / 累得腰酸背痛）；真正可被
                # 定语修饰的裸名词词频高（花朵/态度/天空），不受影响。
                if (self._is_last_content(positions, i + 1)
                        and jieba.dt.FREQ.get(next_word, 0) < _DE_COMPLEMENT_MIN_FREQ):
                    continue
                # 补语保护 C：主谓补语小句的名词性主语（气得脸红 / 急得眼红）——
                # 词频高（脸红 417），频率门槛兜不住，单独收表排除。
                if next_word in _VP_COMPLEMENT_BODY_SUBJECTS:
                    continue
                # 补语保护 D：A + 得 + 多/少/快/慢/很多…（新鲜得多 / 大得多）是
                # 程度/状态补语，多 被 jieba 标 m 会误当裸名词改成 的（CGED 实证）。
                if next_word in VERB_COMPLEMENT_LIKE | DEGREE_COMPLEMENT_WORDS:
                    continue
                self._replace(chars, start, end, '的')
                continue

            # ---------- 规则 0.5：V + 的/得/地 + 名词/代词/区别词 → 的（定语） ----------
            # 标准语法：动词/形容词作修饰语 + 的 + 名词 = 定语（“输入的所有数据”
            # “吃的所有饭”）。这是最高频的 ASR 误用（“输入得所有数据”），必须修正。
            # 触发：prev 为动词（含 vn 名动词），
            #       next 为名/代/数/量词 或 区别词(b：所有/这种/每个…)。
            # 区别词(b) 之前被 ADJ_TAGS 误纳，导致“V+的+所有+N”被规则1/2 错判成“得”，
            # 本规则放在规则1/2 之前，先一步把“的”锁定，杜绝该回归。
            # 保护：prev_word 属“得”构词语素动词（值得/觉得/获得…）→ 跳过，不动。
            # 补语保护（新增，修复杂句误伤）：V+得+N 也可能是结果/程度补语而非定语：
            #   1) 四字及以上短语（跑得满头大汗 / 累得筋疲力尽）
            #   2) 程度指示代词 这么/那么/多么（跑得这么快 / 累得那么厉害）
            #   3) “X不Y”动补结构（睁不开眼睛 / 走不动路 / 听不懂话）
            #   这些“得”必须保留；只有明确短名词/区别词/量词短语（吃得饭/看得书/
            #   输入得所有数据/买得三斤苹果）才是 ASR 把“的”误写为“得”的定语场景。
            if (prev_flag in VERB_TAGS
                    and (next_flag in NOUN_PRON_TAGS or next_flag == 'b')
                    and prev_word not in DE_MORPHEME_VERBS
                    # 排除误标为名词的动作动词（干/走…交规则 3 改“地”）
                    and next_word not in NOUN_TAGGED_ACTION_VERBS
                    # 排除程度/数量补语（很多/不少…交规则 2.6 改“得”）
                    and next_word not in DEGREE_COMPLEMENT_WORDS
                    # 排除已知状态补语词：V+的+多/少/高/慢/对/准/晚… 里这些词常被
                    # jieba 误标为 n/m/b/v（跑的多/说的慢/跑的高），实为补语 → 交
                    # 下方 补语白名单 改“得”。补语词后紧跟内容词（名词/动词）时
                    # 可能是复合名词/名物化（赚的很多钱），保留本规则的“定语”判定。
                    and not (next_word in VERB_COMPLEMENT_LIKE
                             and (i + 2 >= len(positions)
                                  or positions[i + 2][1]
                                  not in (NOUN_PRON_TAGS | VERB_TAGS | ADJ_TAGS | ADV_TAGS)))
                    # 补语信号 1：四字及以上短语
                    and len(next_word) < 4
                    # 补语信号 2：程度指示代词
                    and next_word not in ('这么', '那么', '多么')
                    # 补语信号 3：“X不Y”动补结构（睁不开/走不动/看不清）
                    and not (len(next_word) >= 3 and next_word[1] == '不')
                    # 补语信号 4：后接谓词性成分 → 补语小句（色香味俱全/饿得肚子咕咕叫…）
                    #   V+得+N+谓词：N 是补语小句的主语（做得色香味俱全），保留「得」。
                    #   前向扫描：咕咕叫 是 拟声词(o)+动词，需要多看几个 token。
                    #   而真正的定语场景（输入得所有数据/买得三斤苹果）后接仍是名词，不受影响。
                    and not self._has_predicate_after(positions, i)
                    # 补语信号 5：句尾低词频名词 → 错标为名词的 VP 补语（累得流眼泪）
                    and not (self._is_last_content(positions, i + 1)
                             and jieba.dt.FREQ.get(next_word, 0) < _DE_COMPLEMENT_MIN_FREQ)):
                self._replace(chars, start, end, '的')
                continue

            # ---------- 规则 0.7：A + 得 + A + 的 → 得→的（定语并列） ----------
            # 「相应得成熟的方案 / 相同得重要的目标」：得 前后都是形容词、后面还跟着
            # 「的+名词」，说明两个形容词是并列定语，中间的「得」是「的」的误写。
            # 「高兴得跳起来」（后接动词）、「高兴得很」（后接副词）不在此列，保持补语「得」。
            if (word == '得'
                    and prev_flag in ADJ_TAGS
                    and next_flag in ADJ_TAGS
                    and i + 2 < len(positions)
                    and positions[i + 2][0] == '的'):
                self._replace(chars, start, end, '的')
                continue

            # ---------- 规则 1.4：V + 的/地 + 比 → 得（比字补语：跑的比谁都快） ----------
            # 语法上"比…"跟在动词后只能作补语/状语，V+的+比 必是 得 的补语结构。
            if (word != '得'
                    and prev_flag in COMPLEMENT_PREV_TAGS
                    and next_word == '比'
                    and prev_word not in DE_MORPHEME_VERBS):
                self._replace(chars, start, end, '得')
                continue
            # ---------- 规则 1.5：V + 的/地 + 程度副词 → 得（跑的真快/说的太对） ----------
            if (word != '得'
                    and prev_flag in COMPLEMENT_PREV_TAGS
                    and next_word in DEGREE_ADV_WORDS
                    and prev_word not in DE_MORPHEME_VERBS):
                self._replace(chars, start, end, '得')
                continue

            # ---------- 名物化保护：V + 的 + A + 的（句尾）→ 保留 的 ----------
            # 规则 1/2 会把 大(a) 当状态补语改成 得，但 V+的+A+的 句尾是「A 的那
            # 个」名物化（挑的大的 = 挑的那个大的 / 买的大的 / 拿的新的），的 正确。
            # 区别于 动补+定语：跑得快的人（A 后是 的+名词），得 照改不受影响。
            if (word == '的'
                    and i + 2 < len(positions)
                    and positions[i + 2][0] == '的'
                    and i + 3 >= len(positions)
                    and prev_flag in STRICT_VERB_TAGS
                    and next_flag in ADJ_TAGS):
                continue

            # ---------- 规则 1：V + 得/的 + A/d（状态补语） ----------
            # 适用：跑得快 / 走得很慢（next 是形容词或程度副词引出的补语）
            # 注：不再吃 V+的+V 分支——V+的+V 既可能是"V 的 V"（"吃的饭/说的写的"，
            # 名物化），也可能是"V 地 V"（A+地+V，状语，但那是规则 3 的事）；
            # 该分支与规则 2 概念重叠，直接交给规则 2/3 处理，避免误判。
            # 让位门：如 prev_word 是状语白名单词（被 jieba 误标为 v），交由规则 3 处理
            # 保护：prev_word 属"得"构词语素动词（记得/觉得/值得/获得…）→ 跳过，
            # 否则"记得的很清楚"会被误改成"记得得很清楚"（规则 0.5 之外同样需要）。
            if (word != '得'
                    and prev_flag in COMPLEMENT_PREV_TAGS
                    and next_flag in ADJ_TAGS
                    and prev_word not in ADVERBIAL_ADJ_WHITELIST
                    and prev_word not in DE_MORPHEME_VERBS):
                self._replace(chars, start, end, '得')
                continue
            # 补语白名单：next_word 虽被 jieba 误标为 n/d，但语义上是补语（唱得响）
            if (word != '得'
                    and prev_flag in COMPLEMENT_PREV_TAGS
                    and next_word in VERB_COMPLEMENT_LIKE
                    and prev_word not in ADVERBIAL_ADJ_WHITELIST
                    and prev_word not in DE_MORPHEME_VERBS):
                self._replace(chars, start, end, '得')
                continue
            # 2-token+ lookahead: v+的/地+副词串+补语（走得很慢/说的还挺好/考虑的还不够周到）
            # 向后跳过连续副词（含 不够/不太 等被 jieba 误标为 v 的否定程度副词），
            # 若随后紧跟形容词/补语形容词 → 必是 V+得+补语 结构，改为「得」。
            if (word in ('的', '地')
                    and prev_flag in COMPLEMENT_PREV_TAGS
                    and i + 1 < len(positions)
                    and prev_word not in ADVERBIAL_ADJ_WHITELIST
                    and prev_word not in DE_MORPHEME_VERBS):
                j = i + 1
                while j < len(positions) and (
                        positions[j][1] in ADV_TAGS
                        or positions[j][0] in NEG_DEGREE_ADVERBS):
                    j += 1
                if j < len(positions) \
                        and positions[j][2] - prev_end <= self.MAX_TOKEN_DISTANCE \
                        and (positions[j][1] in ADJ_TAGS
                             or positions[j][0] in ADV_COMPLEMENT_VERBS):
                    self._replace(chars, start, end, '得')
                    continue
            # v+的+副词 句尾 → 得（他跑的很快/跑的快些；jiebai 把 很快 标为 d）。
            # 允许 句号/逗号 跟在副词后（跑的很快。→ 跑得很快。）：标点占位不算。
            if (word == '的'
                    and prev_flag in COMPLEMENT_PREV_TAGS
                    and next_flag in ADV_TAGS
                    and (i + 2 >= len(positions)
                         or positions[i + 2][1] == 'x')
                    and prev_word not in ADVERBIAL_ADJ_WHITELIST
                    and prev_word not in DE_MORPHEME_VERBS):
                self._replace(chars, start, end, '得')
                continue
            # 程度/数量补语：V/A + 的/地 + 很多/不少/太多…（书读的很多/了解地很多）→ 得
            # 保护：后面还跟着名词/谓词时是定语（学的很多知识），不改。
            # 再保护：prev 属“得”构词语素动词（获得/记得/觉得…）→ 跳过，
            # 否则“获得的很多”会被误改成“获得得很多”。
            if (word in ('的', '地')
                    and prev_flag in COMPLEMENT_PREV_TAGS | ADJ_TAGS
                    and next_word in DEGREE_COMPLEMENT_WORDS
                    and prev_word not in DE_MORPHEME_VERBS
                    and (i + 2 >= len(positions)
                         or positions[i + 2][1] not in (NOUN_PRON_TAGS | VERB_TAGS | ADJ_TAGS | ADV_TAGS))):
                self._replace(chars, start, end, '得')
                continue
            # 程度补语（双 token）：V + 的 + 比较/较 + 单字补语 → 得
            # （用的比较多/写的比较快/来的较晚）。jieba 把 比较多 切成 比较+多，
            # 且 多 标为 m，上方整词表匹配不到；prev 必须是动词，排除“我用的钱比较多”。
            if (word == '的'
                    and prev_flag in COMPLEMENT_PREV_TAGS
                    and prev_word not in ADVERBIAL_ADJ_WHITELIST
                    and prev_word not in DE_MORPHEME_VERBS
                    and i + 2 < len(positions)
                    and positions[i + 1][0] in ('比较', '较')
                    and positions[i + 2][0] in _DEGREE_COMPLEMENT_SINGLE):
                self._replace(chars, start, end, '得')
                continue
            # A + 的 + 很（句尾）→ 得（高兴的很/好的很/多的很 → A得很）
            # “X的很”在句尾不可能是合法结构，必是“X得很”的误写，与 prev 无关。
            # 但 prev 为“得”构词语素动词（记得/觉得…）时跳过（记得的很→保持）。
            if (word == '的'
                    and next_word == '很'
                    and prev_word not in DE_MORPHEME_VERBS
                    and (i + 2 >= len(positions)
                         or positions[i + 2][1] not in (NOUN_PRON_TAGS | VERB_TAGS | ADJ_TAGS | ADV_TAGS))):
                self._replace(chars, start, end, '得')
                continue

            # ---------- 规则 2：V + 的 + A → 得（口语误用的最常见） ----------
            if (word == '的'
                    and prev_flag in COMPLEMENT_PREV_TAGS
                    and next_flag in ADJ_TAGS
                    and prev_word not in ADVERBIAL_ADJ_WHITELIST
                    and prev_word not in DE_MORPHEME_VERBS):
                self._replace(chars, start, end, '得')
                continue
            # 补语白名单兜底
            if (word == '的'
                    and prev_flag in COMPLEMENT_PREV_TAGS
                    and next_word in VERB_COMPLEMENT_LIKE
                    and prev_word not in ADVERBIAL_ADJ_WHITELIST
                    and prev_word not in DE_MORPHEME_VERBS):
                self._replace(chars, start, end, '得')
                continue
            # 成语/习语补语：V + 的 + l/i → 得（笑得合不拢嘴/说的一清二楚/打的
            # 一败涂地/急的团团转/唱的红红火火）。l=习用语、i=成语；V+的+成语
            # 在口语里几乎都是动补（的 是 得 的误写），而 V+的+成语 作定语的
            # 场景不存在——定语修饰语是名词/名动词（vn），不会是成语。
            # 注意：i 在 ADV_TAGS 里，「v+的+副词句尾」规则只覆盖 i 在句尾的
            # 情形（一败涂地了 就漏了），这里统一兜住。
            if (word == '的'
                    and prev_flag in COMPLEMENT_PREV_TAGS
                    and next_flag in ('l', 'i')
                    and prev_word not in ADVERBIAL_ADJ_WHITELIST
                    and prev_word not in DE_MORPHEME_VERBS):
                self._replace(chars, start, end, '得')
                continue

            # ---------- 规则 3：A/D + 的 + V → 地（状语）置信度门槛 ----------
            # 修复：允许 ADVERBIAL_ADJ_WHITELIST 词（如"开心"被 jieba 误标为 v）旁路 POS 检查
            # 后词放宽：唱歌/干/走 等动作动词被 jieba 误标为 n，纳入 NOUN_TAGGED_ACTION_VERBS。
            # 动名词保护：后面那个词若作名词（限定词/接名词动词信号）→ 保留「的」；
            # 否则「这个真实的处理」「很多严格的要求」会被误改成「真实地处理/严格地要求」。
            # vn 名动词（检查/分析/研究…）也纳入 next 条件——固定词表已移除它们的
            # 全局替换，这里按上下文判定（做一遍仔细的检查 → 的；仔细的检查 → 地）。
            if (word == '的'
                    and (next_flag in STRICT_VERB_TAGS
                         or next_word in NOUN_TAGGED_ACTION_VERBS
                         or (next_flag == 'vn' and next_word in GERUND_NOUNS)
                         # 成语/习语作状语后词：努力地为国争光（努力 ad）。
                         # 前词必须是形容词/白名单状语（a/ad/an/whitelist）——裸副词
                         # （正常 d）+ 的 + l 标词（男女关系）是名词短语（正常的男女
                         # 关系），不触发。
                         or (next_flag in ('l', 'i')
                             and (prev_flag in ADJ_TAGS
                                  or prev_word in ADVERBIAL_ADJ_WHITELIST))
                         # 为/给/向/对/跟 + 名词短语 + 动词：努力地为...辩护 → 地
                         or (next_word in ('为', '给', '向', '对', '跟')
                             and self._prep_has_verb(positions, i))
                         # 白名单状语 + 的 + 不/没/没有 + A（+ 的 + V）：安静的不痛苦的死
                         # → 安静地不痛苦地死（CGED 实证）。否定词后跟形容词时整段是
                         # 状语链，的 是 地 的误写。
                         or (prev_word in ADVERBIAL_ADJ_WHITELIST
                             and next_word in ('不', '没', '没有')
                             and i + 2 < len(positions)
                             and positions[i + 2][1] in ADJ_TAGS))
                    and next_word not in VERB_TAGGED_NOUNS
                    and (prev_flag in ADJ_TAGS | ADV_TAGS | {'l'}
                         or prev_word in ADVERBIAL_ADJ_WHITELIST)
                    # 保守守卫：句首形容词 + 句尾「可名词化的技术动词」→ 名词短语
                    # 读法（快速的迭代 / 优雅的实现 / 稳定的输出），两种读法都合法，
                    # 宁可不改。有主语（他快速地迭代）或后接宾语时不受影响。
                    # 只保护技术/抽象动词（迭代/运行/输出…），口语动作动词
                    # （唱歌/奔跑/奋斗/买…）不在此列——它们 的→地 必须照常修正
                    # （高兴的唱歌 → 高兴地唱歌 是规则层 MUST）。
                    and not (next_word in _NOUNLIKE_TECH_VERBS
                             and self._is_last_content(positions, i + 1)
                             and self._adj_phrase_initial(positions, i - 1))
                    and not self._gerund_is_nominal(positions, i)):
                if prev_word in ADVERBIAL_ADJ_WHITELIST:
                    # 名词短语读法保护：可作定语的修饰词 + 的 + 名动词（深入的调查/
                    # 系统的分析/及时的反馈/快速的迭代）→ 保留「的」——条件：
                    # ① 无前置主语（_adj_phrase_initial：他快速的迭代 → 改 地）；
                    # ② 名动词不后接宾语（反馈意见/调查情况 = 动宾 → 改 地；
                    #    后接谓语/程度副词/句尾 = 名词短语主语 → 保留 的）。
                    # 情绪词（高兴/快乐）不在 _DE_KEEP_NOMINAL_PREV，唱歌/跳舞
                    # 等口语动作动词不在 GERUND_NOUNS → 照常改 地。
                    if (prev_word in _DE_KEEP_NOMINAL_PREV
                            and (next_word in GERUND_NOUNS
                                 or next_word in _NOUNLIKE_TECH_VERBS)
                            and self._adj_phrase_initial(positions, i - 1)):
                        _has_obj = False
                        if i + 2 < len(positions):
                            _nxt2 = positions[i + 2]
                            if (_nxt2[1] in NOUN_PRON_TAGS
                                    or _nxt2[0] in _NOMINAL_DETERMINERS):
                                _has_obj = True
                        if not _has_obj:
                            continue
                    self._replace(chars, start, end, '地')
                    continue
                # 普通 adj/d 但不在白名单 → 默认不修改（置信度不够，交档位 2）。
                # i/l（若无其事/理所当然 等成语状语）一并放行：成语+的+动词 几乎
                # 必是状语（若无其事的走过去 → 若无其事地走过去，CGED 实证）。
                # CGED 2020/2021 实证双守卫（宁可不改）：
                # ① prev 侧：定语形容词（_DE_KEEP_NOMINAL_PREV：充分的了解 /
                #   正确的决定 / 最好的工作）+ 名动词 + 无动词信号 → 保留 的；
                #   有动词信号（深入地了解我们的文化）→ 照常改 地。
                # ② next 侧：l/i 成语前词 + 名动词 + 无动词信号（男女之间的交往 /
                #   之隔的邻居）→ 保留 的；真成语状语（若无其事的走过去）的
                #   next 是动作动词（走），不在 GERUND_NOUNS → 照常改 地。
                if (prev_flag[:1] in ('a', 'd') or prev_flag in ('i', 'l')) \
                        and prev_word not in _AMBIGUOUS_ADJ_SKIP \
                        and (prev_word not in _DE_KEEP_NOMINAL_PREV
                             or next_word not in GERUND_NOUNS
                             or self._gerund_is_verbal(positions, i)) \
                        and (prev_flag not in ('l', 'i')
                             or next_word not in GERUND_NOUNS
                             or self._gerund_is_verbal(positions, i)):
                    self._replace(chars, start, end, '地')
                    continue

            # ---------- 规则 4：A/D + 地 + 名词短语 → 的 ----------
            # 严格区分 vn 场景：
            #   - next 是纯名词 (n/nr/ns/nt/nz) → 改成「的」（名词短语，“快乐的生活”）
            #   - next 是纯名词 且在 VN_VERB_LIKE 中（被 jieba 误标为 n）→ 保留「地」
            #   - next 是 vn/an → 一律保留「地」：A+地+V 是状语结构（“仔细地检查”
            #     “深入地研究”“全面地分析”），vn 作动词用的频率远高于名词化。
            #     旧版把不在白名单的 vn 改成「的」导致大量误伤，已移除该分支。
            #   - 动量词后缀：被 jieba 合并成名词的“V+动量词”（考虑一下/看一遍）
            #     是“状语+动词短语”，同样保留「地」→ “你再仔细地考虑一下”。
            if word == '地' and (prev_flag in ADJ_TAGS | ADV_TAGS
                                 or prev_word in ADVERBIAL_ADJ_WHITELIST):
                # 白名单旁路：小心/热情/安静 等真形容词被 jieba 误标为 n 时，
                # 也按状语规则处理（小心地处理文件 → 保留「地」），否则会掉进
                # 规则 4.5 的「名词+地+V+N → 的」分支被误改成定语。
                # 动量词保护：next_word 以 一下/一遍/一次… 结尾（V+动量词 被误标为 n）
                if next_word[-2:] in VERB_MEASURE_SUFFIXES or next_word[-3:] in VERB_MEASURE_SUFFIXES:
                    continue
                # 动名词动词化保护：配音这个片段 / 处理了 / 他真实地配音 等
                # 后面那个词虽被 jieba 标为名词，但语境里作动词 → 保留「地」。
                if self._gerund_is_verbal(positions, i):
                    continue
                # 纯名词短语（快乐的生活）→ 的
                # 唱歌/跳舞/跑步 等被 jieba 误标为 n 的动作动词在
                # NOUN_TAGGED_ACTION_VERBS —— 高兴地唱歌 的 地 是状语，
                # 不能按名词短语改「的」（否则双向翻车：高兴地唱歌→高兴的唱歌）。
                if (next_flag in ('n', 'nr', 'ns', 'nt', 'nz')
                        and next_word not in VN_VERB_LIKE
                        and next_word not in NOUN_TAGGED_ACTION_VERBS):
                    self._replace(chars, start, end, '的')
                    continue
                # 动词/名动词/名形词被限定词名词化（这个真实地处理→这个真实的处理）→ 的
                # 仅用限定词信号，不用接名词动词信号，避免把「开始真实地处理」误改。
                if self._gerund_is_nominal(positions, i, include_np_verb=False):
                    self._replace(chars, start, end, '的')
                    continue
                # vn/an 且在白名单 → 保留「地」（程序员的“快乐地编程”“快乐地工作”）

            # ---------- 规则 4.5：代词/名词 + 地 + X → 的/地 ----------
            # 当前词是"地"，前词是代词(r)或名词(n/nr/ns/nt/nz)，这类结构规则 3/4 未覆盖
            # - next 是名词/代词/数词/量词/vn/an → 的（定语："我们地实现方式"→"我们的实现方式"）
            # - next 是严格动词(v/vg/vd/vq/vx) 且 next_next 是名词性 → 的（动宾名词化："我们地实现方式"）
            # - next 是严格动词/形容词/副词 → 地（状语："我们地实现"→"我们地实现"）
            # 保护：前词若在"地点/地方/地址"等合法词中，跳过（需更长匹配）
            # 保护：前词在状语白名单（小心/热情/安静…被 jieba 误标为 n 的真形容词）
            # 时跳过——它们已由规则 4 按状语处理（小心地处理文件 → 保留「地」），
            # 若再进本规则会被「V+N → 动宾名词化」分支误改成「的」。
            if (word == '地'
                    and prev_flag in {'r', 'n', 'nr', 'ns', 'nt', 'nz'}
                    and prev_word not in ADVERBIAL_ADJ_WHITELIST):
                # 排除"地点/地方/地址/地域/土地/地理"等以"地"开头的合法名词
                if prev_word + '地' in {'地点', '地方', '地址', '地域', '土地', '地理', '地势', '地貌', '地板', '地产', '地面', '地下', '地上'}:
                    continue
                # 保守守卫 1：n 标真形容词（全面/公平/客观/科学…jieba 误标为 n）→
                # A+地+V 状语读法（全面地分析问题）与 A+的+V 定语读法（全面的分析）
                # 都合法，宁可不改 → 保留「地」。带不带主语都成立（他全面地分析问题
                # 也不该被改成 他全面的分析问题），所以不看 _adj_phrase_initial。
                if prev_flag == 'n' and prev_word in _N_TAGGED_TRUE_ADJS:
                    continue

                # next 是名词性（含 vn/an）——定语
                if next_flag in NOUN_PRON_TAGS | {'vn', 'an'}:
                    self._replace(chars, start, end, '的')
                    continue
                # next 是严格动词，且再下一个词是 抽象属性名词（方式/方法/思路/
                # 方案…∈ _GERUND_COMPOUND_HEADS）→ 复合名词定语（我们地实现方式
                # → 我们的实现方式）。具体宾语名词（项目/文件/数据/代码）是动宾
                # 结构（规划地实施项目 = 按规划实施项目，状语）→ 保留「地」，
                # 不能按名词短语改 的——否则「规划地实施项目」被误改成
                # 「规划的实施项目」，语义完全变化。
                if (next_flag in STRICT_VERB_TAGS
                        and nxt is not None
                        and i + 2 < len(positions)
                        and positions[i + 2][1] in NOUN_PRON_TAGS | {'vn', 'an'}
                        and positions[i + 2][0] in _GERUND_COMPOUND_HEADS):
                    self._replace(chars, start, end, '的')
                    continue
                # next 是 jieba 误标为动词的常用名词词汇 → 的（如"我们地实现"→"我们的实现"）
                if next_flag in STRICT_VERB_TAGS and next_word in PRONOUN_NOUN_LIKE:
                    self._replace(chars, start, end, '的')
                    continue
                # next 是常用单字动词且无后续名词 → 地（状语："我地写/他地想/我们地走"）
                if next_flag in STRICT_VERB_TAGS and next_word in {'写', '看', '想', '做', '走', '跑', '去', '来', '说', '听', '学', '玩', '干', '吃', '睡', '等', '找', '问', '给', '买', '换', '查', '改', '发', '收', '读', '帮', '借', '还', '送', '拿', '试', '用', '搞', '聊', '修', '调', '测', '编', '译', '推', '拉', '开', '关', '拿', '放'}:
                    self._replace(chars, start, end, '地')
                    continue
                # next 是形容词/副词 → 地（状语："我地快乐/他地认真"极少见，但兜底）
                if next_flag in ADJ_TAGS | ADV_TAGS:
                    self._replace(chars, start, end, '地')
                    continue
                # 默认兜底：视为定语改的（代词/名词+地+X 极大概率是定语）。
                # 但 next 是严格动词时保留「地」（状语）——否则会误伤
                # “安静地等待/小心地干”等正确状语（前词被 jieba 误标为 n/nr）。
                # 例外：前词是真正的代词（我/你/他/我们…）时仍是领属定语 → 的，
                # 找回“我们地实现→我们的实现”（实现被误标为 v）。
                if next_flag not in STRICT_VERB_TAGS or prev_word in _TRUE_PRONOUNS:
                    self._replace(chars, start, end, '的')
                    continue

        return ''.join(chars)

    def correct(self, text: str) -> str:
        """档位 1 主入口：字符级预修正 → fixed → POS → 末尾再 fixed 兑底。"""
        if not text:
            return text
        # 字符级预修正：V + 趋向补语 + 得 + 语气词/句尾 → 的
        # （显示出来得对吗 → 显示出来的对吗；jieba 把 得对 粘成一个 token，
        #   POS 规则层看不到 得，必须先在这里处理）
        text = _DIRECTIONAL_DE_RE.sub(lambda m: m.group(1) + '的' + (m.group(2) or ''), text)
        # 字符级预修正：长 + 的 + 外观形容词 → 长得（jieba 把 长 标成 a，POS 层看不到）
        text = _ZHANG_DE_RE.sub(lambda m: '长' + '得', text)
        text = self.correct_fixed_phrases(text)
        text = self.correct_by_pos(text)
        # 兑底：POS 可能产生了新的 fixed 搭配
        text = self.correct_fixed_phrases(text)
        return text

# 单例
_de_di_de_corrector = DeDiDeCorrector()


# 分句切分：的/地/得 判定依赖「句首/句尾」信号与整句依存，长句里这些信号
# 会因远距离依赖而失效。按标点切成短句逐句判定，规则层窗口不跨句、
# HanLP 也只 parse 短句，长句稳定性明显提升。
_CLAUSE_SPLIT_RE = re.compile(r'([。！？；，、\n]+)')


def _apply_by_clause(text: str, fn) -> str:
    """按标点把长句切成短句，逐句应用 fn，标点原样保留后拼回。"""
    if not text:
        return text
    parts = _CLAUSE_SPLIT_RE.split(text)
    out: List[str] = []
    for part in parts:
        if not part:
            continue
        if _CLAUSE_SPLIT_RE.fullmatch(part):
            out.append(part)
        else:
            out.append(fn(part))
    return ''.join(out)


def correct_de_di_de(text: str) -> str:
    """对外接口：一键纠错（仅规则层；档位 2 由 caller 自行挂载）。

    按短句粒度处理：先切句 → 逐句规则纠错 → 拼回。
    分句前先做字符级预修正：得+标点+连接词 → 的（分句后逗号不可见）。
    """
    if text:
        text = _DE_COMMA_CONNECTIVE_RE.sub(
            lambda m: _de_comma_connective_sub(text, m), text)
    return _apply_by_clause(text, _de_di_de_corrector.correct)


def _keep_de_changes_only(orig: str, hanlp_out: str) -> str:
    """只采纳 HanLP 对「得」的修正，回滚它对「的/地」的改动。

    实证依据（408 条标注语料 + 真实口语样本双路径对比）：
      - HanLP 修对规则漏改 9 条，全部是 的→得（真/太/合不拢嘴 等 jieba 粘词
        漏判的补语结构，动补判定确实需要句法）；
      - HanLP 改坏规则正确 11 条，全部是 的↔地（名动词复合名词：充分的例证 /
        详细的说明文档 / 准确的测量数据 / 充分的准备工作 / 严格的执行标准…——
        规则层用 POS_FIX_DICT 覆写过 jieba 词性的词，HanLP 的标注不认识这些
        覆写，把「的」又改回「地」）。

    结论：的/地 的权威在规则层（词性修正总表 + 复合名词保护都在那里），
    HanLP 只对「得」的判定有净正贡献。故只放行涉及「得」的改动，双向回滚
    的↔地（含 的→地 与 地→的）。
    """
    if orig == hanlp_out:
        return hanlp_out
    from difflib import SequenceMatcher as _SM
    sm = _SM(None, orig, hanlp_out, autojunk=False)
    out = list(hanlp_out)
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag != 'replace':
            continue
        old = orig[i1:i2]
        new = hanlp_out[j1:j2]
        if len(old) == 1 and len(new) == 1 and {old, new} == {'的', '地'}:
            out[j1:j2] = list(old)
    return ''.join(out)


def correct_de_di_de_with_syntax(text: str, syntax_analyzer=None) -> str:
    """档位 1 + 档位 2 串行调用。syntax_analyzer 为 None 时仅走规则。

    按短句粒度处理：先切句 → 每句「规则 → 句法(dep) → 成分句法(const)」→ 拼回，
    避免长句让 HanLP 依存树的长距离依赖断掉。

    必须先做与 correct_de_di_de 相同的分句前字符级预修正
    （得+标点+连接词 → 的）：该正则依赖逗号后的连接词上下文，切句后逗号
    不可见会漏修（人们很喜欢得，还有 → 人们很喜欢的，还有 全管线回归）。

    分工：规则层是 的/地 的权威（词性修正总表 POS_FIX_DICT + 复合名词保护），
    HanLP 只对「得」的判定提供净正贡献——两层的输出都过 _keep_de_changes_only
    （只放行 得 相关改动、回滚 的↔地）。408 条语料实测：纯规则 399 对 →
    叠加 HanLP 后反而降到 397（改坏 11 条名动词复合名词）→ 加本过滤后升到
    407（保留全部 9 条 的→得 修复，消除全部 11 条 的/地 破坏）。

    两者都失败时静默回退到上一层的输出，不抛错不打断。
    """
    if text:
        # 分句前字符级预修正（与 correct_de_di_de 同一来源、同一回调）：
        # 得+标点+连接词 → 的。必须在分句之前，切句后逗号不可见。
        text = _DE_COMMA_CONNECTIVE_RE.sub(
            lambda m: _de_comma_connective_sub(text, m), text)

    def _clause(t: str) -> str:
        t = _de_di_de_corrector.correct(t)
        if syntax_analyzer is None:
            return t
        try:
            t = _keep_de_changes_only(t, syntax_analyzer.correct(t))
        except Exception as e:
            print(f'[warn] HanLP dep 句法纠错失败，已回退到规则结果: {e}')
            return t
        try:
            # 成分句法层：修 dep 啃不动的名动词结构；内部懒加载模型，失败即跳过
            return _keep_de_changes_only(t, syntax_analyzer.correct_by_constituency(t))
        except Exception as e:
            print(f'[warn] HanLP 成分句法纠错失败，已回退到 dep 结果: {e}')
            return t

    return _apply_by_clause(text, _clause)


def extract_dedede_diff(raw: str, corrected: str) -> list:
    """档位 4：抽取 raw → corrected 中包含 的/地/得 的最小 diff 片段。

    Args:
        raw: ASR 原始输出
        corrected: 经规则后处理后的输出

    Returns:
        [(old, new), ...] 仅 old/new 中包含 的/地/得 且 diff_token 总长 <=12
        （仅在语义上是“的地得”调整时才返。其他纠错不动）
    """
    if not raw or not corrected or raw == corrected:
        return []
    from difflib import SequenceMatcher as _SM

    diffs = []
    sm = _SM(a=raw, b=corrected)
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == 'equal':
            continue
        old = raw[i1:i2]
        new = corrected[j1:j2]
        # 只关心含 的/地/得 的调整
        if not any(ch in old + new for ch in '的地得'):
            continue
        # 限长，避免拉入整句差异
        if len(old) > 12 or len(new) > 12:
            continue
        diffs.append((old, new))
    return diffs


