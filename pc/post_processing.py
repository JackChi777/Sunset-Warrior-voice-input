def _cn_num_to_int(word: str):
    """中文数字 0~99 → int；无法解析返回 None。"""
    digit = {'零': 0, '一': 1, '二': 2, '两': 2, '三': 3, '四': 4, '五': 5,
             '六': 6, '七': 7, '八': 8, '九': 9}
    if not word:
        return None
    if '十' in word:
        parts = word.split('十')
        tens = digit.get(parts[0], 1) if parts[0] else 1
        ones = digit.get(parts[1], 0) if len(parts) > 1 and parts[1] else 0
        return tens * 10 + ones
    return digit.get(word)


def _is_mixed_language(text: str) -> bool:
    """检测中英混读：文本同时含中文和 ≥2 个连续拉丁字母。

    SenseVoice 对中英混杂的识别和标点偏弱，检测到混读时 basic 模式
    会附加专门的中英混读修正指令交给 LLM 处理。
    """
    if not text:
        return False
    return bool(re.search(r'[\u4e00-\u9fff]', text) and re.search(r'[A-Za-z]{2,}', text))


