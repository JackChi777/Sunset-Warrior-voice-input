_DE_COMMA_CONNECTIVE_RE = re.compile(r'(得)([，,、])(还有|然后|而且|并且|但是|可是|所以|因此|接着|后来|接下来|此外|再说|其实|不过)')


def _de_comma_connective_sub(text: str, m: 're.Match') -> str:
    """得+标点+连接词 → 的：得 前若是情绪词/构词语素则保留。"""
    start = m.start(1)
    # 情绪词在 得 之前（高兴得）→ 不含 得 的窗口；构词语素含 得（记得/值得）
    # → 含 得 的窗口。两个都查，避免截断漏判。
    tail_exc = text[max(0, start - 3):start]
    tail_inc = text[max(0, start - 3):start + 1]
    for w in _EMOTION_EXCLAM_ADJS:
        if tail_exc.endswith(w):
            return m.group(0)
    for w in DE_MORPHEME_VERBS:
        # 单字 得/要 会匹配一切尾巴（很喜欢得 endswith 得），只对双字及以上构词生效
        if len(w) >= 2 and tail_inc.endswith(w):
            return m.group(0)
    return '的' + m.group(2) + m.group(3)


