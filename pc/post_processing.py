def traditional_to_simplified(text: str) -> str:
    """繁体中文转简体；非中文/英文等原样保留。

    OpenCC 可用时用 OpenCC（覆盖全）；缺失/失败时用内置常用繁简表
    （_T2S_FALLBACK，623 字）兜底，避免繁体字完全不动。
    """
    global _T2S_CONVERTER, _T2S_AVAILABLE
    if not text:
        return text
    if _T2S_AVAILABLE is None:
        try:
            import opencc

            _T2S_CONVERTER = opencc.OpenCC("t2s")
            _T2S_AVAILABLE = True
        except Exception:
            _T2S_AVAILABLE = False
    if _T2S_AVAILABLE and _T2S_CONVERTER is not None:
        try:
            return _T2S_CONVERTER.convert(text)
        except Exception:
            pass
    # OpenCC 缺席/失败：内置常用表兜底
    if any(ch in _T2S_FALLBACK for ch in text):
        return ''.join(_T2S_FALLBACK.get(ch, ch) for ch in text)
    return text


