#   2. 词表双通道——修正产生的新词（jieba 不认识）自动沉淀进 it_terms_user.txt，
#      下次分词不再切碎，规则层 / LLM 提示词一并受益。
# 两条都是纯增量：只往表里加，绝不改动现有规则；diff 抽取（extract_general_diff）
