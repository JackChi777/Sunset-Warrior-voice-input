    def _split_text_smartly(self, text: str, max_len: int = 1500) -> List[str]:
        """
        智能切分长文本，避免撑爆小模型的上下文窗口。
        优先按标点符号（。！？\n）切分，保证句子完整性。
        """
        if len(text) <= max_len:
            return [text]
            
        # 正则：匹配 。！？ 以及换行符，保留分隔符
        # 这样 split 后分隔符会成为独立的元素，方便我们重新拼接
        parts = re.split(r'([。！？\n]+)', text)
        
        chunks = []
        current_chunk = ""
        
        for part in parts:
            # 如果加上当前部分会超过最大长度，且当前块不为空，则先保存当前块
            if len(current_chunk) + len(part) > max_len and current_chunk:
                chunks.append(current_chunk)
                current_chunk = part
            else:
                current_chunk += part
                
        if current_chunk:
            chunks.append(current_chunk)
            
        return chunks

    def process_text_with_prompt(self, text: str, prompt_template: str) -> str:
        """使用指定的提示词模板处理文本"""
        if not text:
            return text

        # 获取术语信息
        hotwords = config_instance.get_hotwords()
        replacements = config_instance.get_replacements()
        
        context_parts = []
        if hotwords:
            # 确保 word 是字符串
            word_list = [str(item.get('word', '')) for item in hotwords if item.get('word')]
            if word_list:
                context_parts.append("专业术语清单：" + "、".join(word_list))
        if replacements:
            # 确保 replacement 描述是字符串
            rep_list = [f"把'{item.get('old', '')}'更正为'{item.get('new', '')}'" 
                       for item in replacements if item.get('old') and item.get('new')]
            if rep_list:
                context_parts.append("替换规则：" + "；".join(rep_list))
            
        term_context = "\n".join(context_parts)
        if term_context:
            full_prompt_template = f"以下是用户提供的一些术语参考：\n{term_context}\n\n在处理下文时，请务必优先参考上述术语。\n\n" + prompt_template
        else:
            full_prompt_template = prompt_template

        # 1. 智能切分长文本
        chunks = self._split_text_smartly(text, max_len=600)
        processed_chunks = []
        
        print(f"[Info] 文本较长，已切分为 {len(chunks)} 个片段进行处理...")

        # 2. 分段处理
        for i, chunk in enumerate(chunks):
            # 替换提示词中的变量
            prompt = full_prompt_template.replace("{text}", chunk)
            print(f"[Processing] 正在处理第 {i+1}/{len(chunks)} 段...")
            result = self.call_llm(prompt)
            # 如果处理失败（返回空），则保留原文，防止丢字
            processed_chunks.append(result if result else chunk)
            
        # 3. 合并结果
        return "".join(processed_chunks)

    def correct_common_errors(self, text: str) -> str:
        """
        修正常见错误：
        1. 的/地/得 - 使用智能纠错器（固定词表 + 词性规则 + 可选 HanLP 增强）
        2. 常见错别字/异形词 - 固定词表
        3. 用户自定义替换
        4. 同音字纠错（ConfusionSet + jieba）
        """
        if not text:
            return text

        # 1. 的/地/得 智能纠错：档位 1 固定 + POS，档位 2 可选句法增强
        use_syntax = False
        try:
            use_syntax = bool(
                config_instance.get('post_processing.syntax_analyzer.enabled', False)
            )
        except Exception:
            use_syntax = False

        if use_syntax:
            try:
                from syntax_analyzer import get_default_analyzer  # type: ignore
                text = correct_de_di_de_with_syntax(text, get_default_analyzer())
            except Exception as e:
                print(f'[warn] syntax_analyzer 加载失败，回退纯规则: {e}')
                text = correct_de_di_de(text)
        else:
            text = correct_de_di_de(text)

        # 档位 4.5：热词 / 术语 fuzzy 替换（『K八S』→『K8s』、ASR 同音异形还原）
        # 始终执行，不依赖 syntax analyzer 开关
        try:
            text = apply_it_term_fuzzy_replace(text, _DEFAULT_TERMS_PATH)
        except Exception as e:
            print(f'[warn] fuzzy 替换异常（已兑底未替换）: {e}')

        # 2. 其他常见错别字/异形词（保留原有词表中非的地得部分）
        # 始终执行，不依赖 syntax analyzer 开关；带子串守卫（_apply_typo_fixes）
        text = _apply_typo_fixes(text)

        # 3. 档位 5：同音字纠错（ConfusionSet + jieba 三级评分，替代被 INT8 量化搞残的 MacBERT4CSC）。
        # 纯 CPU、零额外模型依赖，毫秒级响应。
        # 始终执行，不依赖 syntax analyzer 开关
        try:
            text = correct_with_csc(text)
        except Exception as e:
            print(f'[warn] 同音字纠错失败（已兑底为原文）: {e}')

        # 3.5 档位 5.5：异形词规范层（《第一批异形词整理表》GF 1001-2001）
        # 放在 CSC 之后（CSC 先修同音字，这里再归一同音异形词），用户替换之前
        # （用户手动配置的替换优先级更高）。
        try:
            if config_instance.get('post_processing.yixing_words', True):
                text = apply_yixing_standardization(text)
        except Exception as e:
            print(f'[warn] 异形词规范层失败（已兑底为原文）: {e}')

        # 4. 用户自定义替换（来自设置 → 术语管理 → 文本强制替换）
        # 放在同音字纠错之后，防止用户替换被同音字纠错再改回去
        user_replacements = config_instance.get_replacements()
        for item in user_replacements:
            old_word = item.get("old")
            new_word = item.get("new")
            if old_word and new_word and old_word in text:
                text = text.replace(old_word, new_word)
                print(f"[术语替换] '{old_word}' → '{new_word}'")

        # 4.5 自学习规则（B 档确认制）：已升级的精确规则 + 其同音变体。
        # 优先级低于用户手动替换；读取/应用失败一律保留原文。
        try:
            text = apply_learned_rules(text)
        except Exception as e:
            print(f'[warn] 自学习规则应用失败: {e}')

        return text

    def normalize_chinese_numbers(self, text: str) -> str:
        """将中文数字转换为阿拉伯数字（支持口语数字和普通数值）"""
        if not text:
            return text
        
        # --- 0. 保护逻辑：防止特定量词前的中文数字被转换 ---
        # 如果数字后面跟着这些字，就保持中文，不转阿拉伯数字
        # 例如：一下、一个、一头、一条、两遍
        # 基于用户提供的专业量词表进行扩充
        protected_quantifiers = "个块只本辆瓶帆杯看听闻双件张碗种匹头条边位项名步些家点场句段分处片套座部则层样群届支批篇番股首声颗组盏口把间笔所对根幅出道拨队堆阵面台局棵盒户栋节封班盘副趟款团束门架顿堵壶朵排份具包罐粒卷堂起枝株轮桌桶滴串列箱扇下遍回次"
        
        # 使用占位符临时替换这些受保护的词组
        protected_map = {}
        
        def protect_match(match):
            # 生成一个唯一的占位符
            key = f"__PROTECTED_{len(protected_map)}__"
            protected_map[key] = match.group()
            return key

        # 正则匹配：[中文数字] + [保护量词]
        # 这里的正则涵盖了 一~九、十、两
        pattern = f"([一二三四五六七八九十两]+[{protected_quantifiers}])"
        text = re.sub(pattern, protect_match, text)
        # ------------------------------------------------

        # --- 0.5 成词保护：中文数字是「非数字词/成语」的一部分时保持原样 ---
        # 先于 tens/teens/单字映射执行，否则 一般→1般、一定→1定、唯一→唯1、
        # 星期一→星期1、一丝不苟→1丝不苟、三心二意→3心2意、十全十美→10全10美 全崩。
        for w in sorted(_CN_NUM_PROTECT_WORDS, key=len, reverse=True):
            if w in text:
                key = f"__PROTECTED_{len(protected_map)}__"
                protected_map[key] = w
                text = text.replace(w, key)
        for rx in _CN_NUM_PROTECT_RES:
            text = re.sub(rx, protect_match, text)
        # ------------------------------------------------

        # --- 0.6 GB/T 15835：百分比 百分之N → N%（百分之百/二百/三百 是惯用语，保持）---
        # 必须先于 tens/teens/单字映射，否则 三十→30 后 百分之 后接的是阿拉伯数字
        # 就再也匹配不上了。
        def replace_percent(match):
            num_word = match.group(1)
            # 百分之百/二百/三百/两百 是口语惯用语，保持中文（避免 2%百 残片）
            if num_word in ('百', '二百', '三百', '两百'):
                # 放进保护占位：后续 tens/单字映射不能把 二百 再打成 2百
                key = f"__PROTECTED_{len(protected_map)}__"
                protected_map[key] = match.group()
                return key
            v = _cn_num_to_int(num_word)
            if v is None:
                return match.group()
            return f"{v}%"

        # 百 必须进字符类：百分之二百 整体匹配后由守卫保持，否则 百分之二 先被转掉
        text = re.sub(r'百分之([一二三四五六七八九十两百]+)', replace_percent, text)
        # ------------------------------------------------

        # 1. 简单的0-9映射 (针对 "二七零" -> "270", "一b" -> "1b" 这种场景)
        # 注意：这里会优先把所有独立的数字字符转掉，这通常是用户想要的（尤其是在说代码或型号时）
        digit_map = {
            '零': '0', '一': '1', '二': '2', '三': '3', '四': '4',
            '五': '5', '六': '6', '七': '7', '八': '8', '九': '9'
        }
        
        # 2. 处理 "十" 的特殊情况 (简单的十/百转换，复杂的建议留给LLM)
        # 这里的逻辑主要是为了处理口语中最常见的 "二十" -> "20", "十三" -> "13"
        # 复杂的 "一万两千" 如果没有LLM，写规则会非常复杂，这里只做轻量级处理
        
        # 策略：先处理 "十" 相关的组合，再处理剩下的单字
        
        # 处理 "二十"..."九十" (Tens)
        # 匹配模式：[二-九]十[一-九]? 
        # 例如：二十 -> 20, 二十一 -> 21
        def replace_tens(match):
            val = match.group()
            first = digit_map.get(val[0], '')
            if len(val) == 2: # 二十
                return f"{first}0"
            elif len(val) == 3: # 二十一
                last = digit_map.get(val[2], '')
                return f"{first}{last}"
            return val

        text = re.sub(r'[二三四五六七八九]十[一二三四五六七八九]?', replace_tens, text)

        # 处理 "十X" (Teens)
        # 匹配模式：十[一-九]?
        # 例如：十 -> 10, 十一 -> 11
        def replace_teens(match):
            val = match.group()
            if len(val) == 1: # 十
                return "10"
            elif len(val) == 2: # 十一
                last = digit_map.get(val[1], '')
                return f"1{last}"
            return val
            
        text = re.sub(r'(?<![一二三四五六七八九])十[一二三四五六七八九]?', replace_teens, text)

        # 3. 处理剩下的单字 (如 "二七零", "一b")
        for cn, ar in digit_map.items():
            text = text.replace(cn, ar)
            
        # --- 4. 还原保护的词组 ---
        for key, value in protected_map.items():
            text = text.replace(key, value)
            
        return text

    def process_text_mode(self, text: str, mode: str) -> str:
        """根据模式处理文本（引擎路径：委托 proofreading.proofread）。

        Args:
            text: 原始文本（已通过ASR+标点处理）
            mode: 处理模式 ("none", "basic", "custom")

        Returns:
            处理后的文本

        引擎层（proofreading.py）持有阶段流水线唯一实现；此处只是语音应用的
        一个调用方（静默取 result.text）。LLM 阶段通过 llm_caller 注入本实例的
        process_text_with_prompt，与历史行为一致。parity 测试守护行为不漂移。
        """
        if not text:
            return text
        try:
            from proofreading import proofread  # 延迟导入避免循环依赖
            result = proofread(text, mode=mode,
                               llm_caller=self.process_text_with_prompt)
            return result.text
        except Exception as e:
            # 引擎异常时优雅降级：保留原文（各阶段内部已各自兜底，此处是最后防线）
            print(f'[warn] 校对引擎调用失败，已降级为原文: {e}')
            return text

    def call_llm(self, prompt: str) -> str:
        """按 llm.backend 路由润色请求：openai → OpenAI 兼容 API；ollama → 原生 API。"""
        if self.llm_backend == "openai":
            return self._call_openai_compatible(prompt)
        return self.call_ollama(prompt)

    def call_ollama(self, prompt: str) -> str:
        """调用 Ollama 原生 /api/generate（兼容旧配置，backend=ollama 时使用）。"""
        try:
            # 打印实际发送给模型的Prompt，用于调试
            print(f"[DEBUG] Sending prompt to Ollama ({self.model_name}):\n{prompt}\n-------------------")
            
            payload = {
                "model": self.model_name,
                "prompt": prompt,
                "stream": False
            }
            response = requests.post(self.ollama_url, json=payload, timeout=30)
            if response.status_code == 200:
                result = response.json()
                return result.get("response", "").strip()
            else:
                print(f"Ollama API错误: {response.status_code} - {response.text}")
                return ""
        except requests.exceptions.Timeout:
            print("Ollama请求超时")
            return ""
        except Exception as e:
            print(f"调用Ollama失败: {str(e)}")
            return ""

    def _call_openai_compatible(self, prompt: str) -> str:
        """调用 OpenAI 兼容 /chat/completions 接口（本地端口 / vLLM / LM Studio / 云端）。

        base_url 自动补 /v1（http://127.0.0.1:8000 → http://127.0.0.1:8000/v1/chat/completions）。
        失败返回空串，调用方保留原文，不丢字。
        """
        base = (self.llm_openai_base_url or "").strip().rstrip("/")
        if not base:
            print("[warn] LLM 后端为 OpenAI 兼容但未配置 base_url，已跳过润色（保留原文）")
            return ""
        if not base.endswith("/v1"):
            base = base + "/v1"
        url = base + "/chat/completions"
        model = self.llm_openai_model or self.model_name
        payload = {
            "model": model,
            "messages": [{"role": "user", "content": prompt}],
            "stream": False,
        }
        headers = {"Content-Type": "application/json"}
        if self.llm_openai_api_key:
            headers["Authorization"] = f"Bearer {self.llm_openai_api_key}"
        try:
            print(f"[DEBUG] Sending prompt to OpenAI-compatible ({url}, model={model})")
            response = requests.post(
                url, json=payload, headers=headers, timeout=self.llm_openai_timeout
            )
            if response.status_code != 200:
                print(f"[warn] LLM API 错误: {response.status_code} - {response.text[:200]}")
                return ""
            data = response.json()
            try:
                return data["choices"][0]["message"]["content"].strip()
            except (KeyError, IndexError, TypeError):
                print(f"[warn] LLM API 响应格式异常: {str(data)[:200]}")
                return ""
        except requests.exceptions.Timeout:
            print("LLM 请求超时")
            return ""
        except Exception as e:
            print(f"调用 LLM API 失败: {e}")
            return ""

    def process_text(self, text: str) -> str:
        """使用配置的后处理模式处理文本（向后兼容）"""
        mode = config_instance.get_post_processing_mode()
        return self.process_text_mode(text, mode)

