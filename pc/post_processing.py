def _load_jieba_user_dict() -> int:
    """加载专名词典到 jieba。档位 1 命中率提升。

    说明：
    - 优先走 jieba.add_word（分词字典）+ jieba.posseg.add_word（词性字典）双写。
    - 某些 jieba 版本不暴露 jieba.posseg.add_word（AttributeError），
      此时 posseg 同步静默跳过，靠 FIXED 表兑底。
    - P0 fix：仅在 jieba.add_word 全部成功时才将 _done=True。
      任一失败则 _done 保持 False，下次调用自动重试（避免词条半生效永久锁死）。
    """
    if getattr(_load_jieba_user_dict, '_done', False):
        return 0
    # jieba.posseg 在某些版本没有暴露 add_word；用 getattr 兜底，避免 Pylance 静态告警
    _pseg_add_word = getattr(pseg, 'add_word', None)  # type: ignore[attr-defined]
    all_ok = True
    try:
        for entry in JIEBA_USER_DICT_ENTRIES:
            parts = entry.split()
            if len(parts) < 2:
                continue
            word, tag = parts[0], parts[1]
            freq = int(parts[2]) if len(parts) >= 3 else 1000
            try:
                jieba.del_word(word)
            except Exception:
                pass
            try:
                jieba.add_word(word, freq=freq, tag=tag)
            except Exception as e:
                print(f'[warn] jieba.add_word 失败: {entry}: {e}')
                all_ok = False
            if _pseg_add_word is not None:
                try:
                    _pseg_add_word(word, tag, freq=freq)
                except Exception as e:
                    print(f'[warn] jieba.posseg.add_word 失败: {entry}: {e}')
        # 词性修正总表：同样写入 jieba，保证分词/外部 posseg 标注一致
        for word, tag in POS_FIX_DICT.items():
            try:
                jieba.del_word(word)
            except Exception:
                pass
            try:
                jieba.add_word(word, freq=1000, tag=tag)
            except Exception as e:
                print(f'[warn] jieba.add_word 失败: {word}: {e}')
                all_ok = False
            if _pseg_add_word is not None:
                try:
                    _pseg_add_word(word, tag, freq=1000)
                except Exception as e:
                    print(f'[warn] jieba.posseg.add_word 失败: {word}: {e}')
        if all_ok:
            _load_jieba_user_dict._done = True  # type: ignore[attr-defined]
        n = len(JIEBA_USER_DICT_ENTRIES) + len(POS_FIX_DICT)
        print(f'[info] jieba 用户词典加载成功：{n} 条' if all_ok else f'[warn] jieba 用户词典部分失败: {n} 条')
        return n if all_ok else 0
    except Exception as e:
        print(f'[warn] jieba 用户词典加载失败: {e}')
        return 0


try:
    _load_jieba_user_dict()
except Exception:
    pass


