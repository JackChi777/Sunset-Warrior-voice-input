def _build_fuzzy_list(term_path: Optional[str] = None) -> list:
    """构建 POST-stage fuzzy 替换列表。仅包含『英文术语』，中文术语交给 jieba 处理。

    Returns: [(term_lower, term_canonical, score), ...]
    """
    path = term_path or _DEFAULT_TERMS_PATH
    if not path or not os.path.exists(path):
        return []
    out: list = []
    try:
        with open(path, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith('#'):
                    continue
                parts = line.split()
                if not parts:
                    continue
                word = parts[0]
                try:
                    score = float(parts[1]) if len(parts) > 1 else 2.0
                except (ValueError, IndexError):
                    score = 2.0
                # 仅处理含字母的术语：K8s、PyTorch、MySQL、TypeScript
                has_alpha = any('a' <= c.lower() <= 'z' for c in word)
                if not has_alpha:
                    continue
                out.append((word.lower(), word, score))
    except Exception as e:
        print(f'[warn] 构建 fuzzy 列表失败: {e}')
    return out


def apply_it_term_fuzzy_replace(text: str, term_path: Optional[str] = None) -> str:
    """POST 阶段：把 ASR 输出的『同音异形』还原为权威术语（如 'K 八 S' → 'K8s'）。

    依赖 fuzzy_cache；使用时需先 warmup（或者本函数会龵主动构建）。
    """
    global _FUZZY_CACHE
    if _FUZZY_CACHE is None:
        _FUZZY_CACHE = _build_fuzzy_list(term_path)
    if not text or not _FUZZY_CACHE:
        return text

    import re as _re
    # 抓探 EN-Cn-EN 混合 + EN 0-N-EN 空格分隔 ASR 详出。
    # 上限提到 32 （『HyperparameterOptimisation」27 / 『superconducting_materials」25 不会被截）。
    _TOKEN_RE = _re.compile(r'[A-Za-z][A-Za-z0-9._+\-\u4e00-\u9fff ]{0,31}', _re.UNICODE)
    tokens = list(_TOKEN_RE.finditer(text))
    if not tokens:
        return text

    # 逐 token：case-insensitive 精确匹配优先，其次模糊
    out = []
    last = 0
    for m in tokens:
        out.append(text[last:m.start()])
        word = m.group()
        word_lower = word.lower()
        canonical = None
        # case-insensitive exact
        for term_lower, term_canon, _score in _FUZZY_CACHE:
            if term_lower == word_lower:
                canonical = term_canon
                break
        # fuzzy：先 cn-digit 还原 + cn-strip，再 Levenshtein（按 term 长度分级阈值）
        if canonical is None:
            # 含非汉数字中文（术语+中文粘连，Python是/用Python写代码）→ 不参与
            # 模糊匹配，原样保留（防止吞掉术语后面的中文）。
            has_cn_context = any(
                '\u4e00' <= ch <= '\u9fff' and ch not in _CN_DIGIT_MAP
                for ch in word)
            if not has_cn_context:
                for term_lower, term_canon, score in _FUZZY_CACHE:
                    if not term_lower or term_lower[0] != word_lower[0]:
                        continue
                    if _try_cn_separated_match(word, term_lower):
                        canonical = term_canon
                        break
                    limit = _levenshtein_threshold_for_term(term_lower)
                    # 高权重（>=4.0）的术语 严拼阈值 调低；低权重（<=2.0）的可以略宽。
                    # limit==0（短术语）不回升，保持仅精确+cn-separated
                    if score >= 4.0 and limit > 0:
                        limit = max(1, limit - 1)
                    if _quick_levenshtein_le(word_lower, term_lower, limit):
                        canonical = term_canon
                        break
        out.append(canonical if canonical else word)
        last = m.end()
    out.append(text[last:])
    return ''.join(out)


def _quick_levenshtein_le(a: str, b: str, limit: int) -> bool:
    """编辑距离 ≤ limit 的 O(N^2) 判断。供 fuzzy 过滤使用，limit 根据词表长度动态赋。"""
    if a == b:
        return True
    la, lb = len(a) + 1, len(b) + 1
    if abs((la - 1) - (lb - 1)) > limit:
        return False
    # 标准 DP，但只走两行，并提前剪枝
    prev = list(range(lb))
    for i in range(1, la):
        cur = [i] + [0] * (lb - 1)
        # 剪枝：本行最小代价如果已超 limit，跳过
        row_min = la + lb
        for j in range(1, lb):
            cost = 0 if a[i - 1] == b[j - 1] else 1
            cur[j] = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + cost)
            if cur[j] < row_min:
                row_min = cur[j]
        if row_min > limit:
            return False
        prev = cur
    return prev[-1] <= limit


# 汉数字 → 阿拉伯数字映射（限常见单字；覆盖「K八S」→「k8s」这类 ASR 误拼）
_CN_DIGIT_MAP = {
    '零': '0', '一': '1', '二': '2', '三': '3', '四': '4',
    '五': '5', '六': '6', '七': '7', '八': '8', '九': '9',
    '两': '2', '十': '10', '百': '100',
}


def _quick_levenshtein_le2(a: str, b: str) -> bool:
    """Levenshtein ≤ 2 的转调函数（保留原名以免外部调用者找不到）。"""
    return _quick_levenshtein_le(a, b, 2)


def _normalize_word_with_cn_digit(word: str) -> str:
    """把词中的汉数字转成阿拉伯数字、去掉所有空格，获得『技术还原后的形式』。

    例：『K八S』→『k8s』、『二十点五』→『205』、『Python8』→python8。
    中文非数字字符（『免拆/kafk a 高』中的『高』）是上下文助词，需要保留作为后续锚点
    判断，这里采取：中文、静默保留首末跳过不万一。
    """
    if not word:
        return word
    out: list = []
    for ch in word.lower():
        if '\u4e00' <= ch <= '\u9fff':
            mapped = _CN_DIGIT_MAP.get(ch)
            if mapped:
                out.append(mapped)  # 『八』→『8』
            # 其他中文不静默 drop，会丢失语境。保留原 API // 下沉为 byte 避免可见阄
            continue
        if ch == ' ':
            continue
        out.append(ch)
    return ''.join(out)


def _try_cn_separated_match(word: str, term_lower: str) -> bool:
    """检测『word』是否为『term_canonical_lower』中插入了中文 / 汉数字 / 空格的变体。

    例：『K八S』→『k8s』（汉数字八→8后剩『ks』，词中有 8 -> k8s）；
        『P y t o r c h』→『pytorch』；
        『K 8 S』→『k8s』。
    要求头字符同，不然视为不匹配（避免误拼入候选）。

    词中只允许 汉数字 + 空格 插入（K八S/K 8 S）；普通中文（是/和/代码…）
    说明是『术语+中文』粘连（Python是/用Python写代码），一律不匹配，
    防止吞掉术语后面的中文（fuzz 发现的吞字 bug）。
    """
    if not word or not term_lower:
        return False
    if not term_lower[0].isalnum():
        return False
    first = word.lstrip()[0:1].lower() if word.lstrip() else ''
    if first != term_lower[0]:
        return False
    for ch in word:
        if '\u4e00' <= ch <= '\u9fff' and ch not in _CN_DIGIT_MAP:
            return False
    return _normalize_word_with_cn_digit(word) == term_lower


def _levenshtein_threshold_for_term(term_lower: str) -> int:
    """根据 term 长度返回 Levenshtein 推荐阈值：长词放宽，短词收紧以避免误拼。

    n<=3（Go/C/K8s）：0——只允许精确 + cn-separated，禁止字母级模糊，
    否则 got/god → Go 这类英文常用词会被吞字（fuzz 发现的吞字 bug）。
    """
    n = len(term_lower)
    if n <= 3:
        return 0
    if n <= 4:
        return 1
    return 2


